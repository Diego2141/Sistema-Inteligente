# Estas funciones cierran el pendiente "estimar ρ_s por régimen" y dan el
# loader de los parquets reales que guarda step005_walk_forward_cv_4.py
# (preds_test_fold*.parquet, ya con columnas regimen_hmm/regimen_sigma/
# año_corte_regimen) y step005_validar_hmm_*.py (transmat_hmm_<banco>.parquet).

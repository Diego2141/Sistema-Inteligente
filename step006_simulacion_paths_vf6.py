# PARTE 4 — Simulación de un path via recursión AR(1) + PPF de split-t
# ══════════════════════════════════════════════════════════════════════════════
#
# Equivalencia con cópula gaussiana (ver HTML del marco metodológico):
#
#   La recursión  z_k = ρ_s(k) · z_{k-1} + √(1-ρ_s(k)²) · w_k
#   ES la factorización de Cholesky de una Σ AR(1) con ρ variable en el tiempo,
#   implementada como el algoritmo de Thomas (O(n)) en lugar de Cholesky general
#   (O(n³)). La dependencia está en la salida z; los insumos w_k son independientes.

def simular_un_path(
    fecha_t:          pd.Timestamp | str,
    horizontes:       np.ndarray,
    regimenes_path:   np.ndarray,
    rho_por_regimen:  dict[int, float],
    distribuciones:   dict[tuple, AzzaliniT | SplitT],
    rng:              np.random.Generator,
) -> np.ndarray:
    """
    Genera un path de residuos/flujos para los horizontes pedidos desde fecha_t.

    Parámetros
    ----------
    fecha_t         : fecha de origen.
    horizontes      : array [1, 2, ..., H_MAX] (índices del path).
    regimenes_path  : array de estados de régimen por cada horizonte.
    rho_por_regimen : {estado: ρ_s}, correlación AR(1) por régimen.
    distribuciones  : dict {(fecha_t, h): SplitT} — marginales calibradas.
    rng             : generador de números aleatorios.

    Devuelve
    --------
    array de shape (len(horizontes),) con residuos simulados en escala real.
    """
    n   = len(horizontes)
    w   = rng.standard_normal(n)          # ruido independiente (insumo de Thomas)
    z   = np.empty(n)
    z[0] = w[0]

    for k in range(1, n):
        rho   = rho_por_regimen.get(regimenes_path[k], 0.0)
        z[k]  = rho * z[k - 1] + np.sqrt(max(1.0 - rho**2, 0.0)) * w[k]

    u = stats.norm.cdf(z)                 # uniforme correlacionada [0,1]

    residuos = np.empty(n)
    for k, h in enumerate(horizontes):
        key  = (pd.Timestamp(fecha_t), int(h))
        dist = distribuciones.get(key)
        if dist is None:
            residuos[k] = 0.0
        else:
            residuos[k] = float(dist.ppf(np.clip(u[k], 1e-7, 1.0 - 1e-7))[0])

    return residuos



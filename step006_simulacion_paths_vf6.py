# PARTE 7 — Backtest: las tres piezas
# ══════════════════════════════════════════════════════════════════════════════

def backtest_pieza1_violaciones(
    df_sim:    pd.DataFrame,
    tau_col:   float = 0.05,
    ventana:   int = 22,
    lag_nw:    int | None = None,
) -> dict:
    """
    Pieza 1: tasa de violación con corrección Newey-West por solapamiento.

    Selecciona los registros donde tau == tau_col y ventana == ventana.

    BUG CORREGIDO: una "violación" depende de qué cola representa tau_col.
    Para tau_col<0.5 (cola inferior, p.ej. Q05 — el caso de uso de este
    proyecto: estrés de liquidez = el flujo cae POR DEBAJO del piso), la
    violación es I_t=1(realizado < percentil_predicho) — el realizado rompió
    el piso de estrés. La versión anterior usaba ">" sin importar la cola,
    lo que daba tasa_empirica≈1-τ (cerca de 0.95, no 0.05) y comparaba eso
    contra τ sin sentido, marcando pasa=False siempre sin decir nada real
    sobre la calibración del modelo. Para tau_col>0.5 (cola superior) la
    violación correcta es la dirección opuesta, I_t=1(realizado > predicho).

    Con la dirección correcta, P(I_t=1) debe acercarse a τ bajo buena
    calibración, y ahí sí la comparación contra τ es válida.

    Calcula la tasa empírica con varianza corregida por autocovarianza hasta
    lag_nw (default = ventana).

    Devuelve
    --------
    dict con: tasa_empirica, tau_nominal, ic95_lo, ic95_hi, pasa, n,
              descripcion.
    """
    sub = df_sim[
        (df_sim["tau"] == tau_col) & (df_sim["ventana"] == ventana)
    ].sort_values("fecha_t")

    if len(sub) < 5:
        return {"error": "insuficientes observaciones"}

    if tau_col < 0.5:
        # Cola inferior (estrés de liquidez): violación = romper el piso.
        I = (sub["y_realizado_acum"] < sub["percentil_acum"]).astype(float).values
    else:
        # Cola superior: violación = superar el techo.
        I = (sub["y_realizado_acum"] > sub["percentil_acum"]).astype(float).values
    n   = len(I)
    pi  = float(I.mean())

    # Varianza Newey-West con kernel de Bartlett
    L   = lag_nw if lag_nw is not None else ventana
    L   = min(L, n // 2)
    I_c = I - pi
    nw_var = float(np.dot(I_c, I_c)) / (n ** 2)
    for k in range(1, L + 1):
        w_k = 1.0 - k / (L + 1.0)
        cov_k = float(np.dot(I_c[k:], I_c[:n - k])) / (n ** 2)
        nw_var += 2.0 * w_k * cov_k
    nw_var = max(nw_var, 1e-12)
    se  = np.sqrt(nw_var)
    lo  = pi - 1.96 * se
    hi  = pi + 1.96 * se
    pasa = (lo <= tau_col <= hi)

    return {
        "tasa_empirica": round(pi, 4),
        "tau_nominal":   tau_col,
        "ic95_lo":       round(lo, 4),
        "ic95_hi":       round(hi, 4),
        "pasa":          bool(pasa),
        "n":             n,
        "ventana_dias":  ventana,
        "lag_nw":        L,
        # Arrays crudos para reporte (series temporal de violaciones)
        "I_indicators":  I.tolist(),
        "fechas_t":      sub["fecha_t"].tolist(),
        "descripcion":   (
            f"Ventana {ventana}d | τ={tau_col:.2f} | "
            f"tasa emp={pi:.1%} vs nominal={tau_col:.1%} | "
            f"IC95%=[{lo:.3f},{hi:.3f}] | "
            f"{'✓ PASA' if pasa else '✗ FALLA'}"
        ),
    }

def backtest_pieza2_duraciones(
    df_sim:   pd.DataFrame,
    tau_col:  float = 0.05,
    ventana:  int = 22,
) -> dict:
    """
    Pieza 2: test de duraciones de Christoffersen-Pelletier.

    Ajusta una distribución exponencial (geométrica en continuo) con
    parámetro τ (bajo H0 de independencia) y una Weibull libre (b libre).
    El LR test tiene distribución χ²(1) bajo H0.

    Bajo H0: duraciones siguen Exp(τ), es decir b=1 en la Weibull.
    Si b < 1: violaciones agrupadas (peor para decisiones de liquidez).
    Si b > 1: violaciones dispersas (modelo conservador).

    Devuelve dict con: n_violaciones, duraciones_medias, b_weibull,
    lr_stat, p_valor, pasa_independencia, descripcion.
    """
    sub = df_sim[
        (df_sim["tau"] == tau_col) & (df_sim["ventana"] == ventana)
    ].sort_values("fecha_t")

    # Mismo criterio de dirección que backtest_pieza1_violaciones: para
    # tau_col<0.5 (cola inferior, estrés de liquidez) la violación es romper
    # el piso; para tau_col>0.5, superar el techo.
    if tau_col < 0.5:
        I = (sub["y_realizado_acum"] < sub["percentil_acum"]).astype(float).values
    else:
        I = (sub["y_realizado_acum"] > sub["percentil_acum"]).astype(float).values
    n = len(I)
    if n < 10:
        return {"error": "insuficientes observaciones"}

    # Instantes de violación
    t_viol = np.where(I == 1)[0]
    if len(t_viol) < 3:
        return {"error": "insuficientes violaciones para test de duraciones"}

    # Duraciones entre violaciones (incluye censura al inicio y al final)
    durs = np.diff(t_viol).astype(float)
    if len(durs) < 2:
        return {"error": "demasiado pocas duraciones"}

    # Log-verosimilitud bajo H0: Exp con λ=τ (geometrica aprox continua)
    tau_nom = tau_col
    def loglik_exp(durs, lam):
        return float(np.sum(np.log(lam) - lam * durs))

    def loglik_weibull(durs, a, b):
        if a <= 0 or b <= 0:
            return -np.inf
        return float(np.sum(np.log(b) + np.log(a) + (b-1)*np.log(durs) - a*durs**b))

    # Ajuste libre de Weibull
    try:
        def neg_ll(params):
            a, b = params
            if a <= 0 or b <= 0:
                return 1e12
            return -loglik_weibull(durs, a, b)

        res = optimize.minimize(
            neg_ll, [tau_nom, 1.0], method="L-BFGS-B",
            bounds=[(1e-6, 10.0), (1e-3, 10.0)],
            options={"maxiter": 500},
        )
        a_hat, b_hat = res.x
        ll_libre = -res.fun
    except Exception as _e_wb:
        logger.debug(f"backtest_pieza2: fallo ajuste Weibull → "
                     f"{type(_e_wb).__name__}: {_e_wb}")
        return {"error": "fallo ajuste Weibull"}

    # Log-verosimilitud restringida H0: b=1, a=τ (exponencial)
    ll_h0 = loglik_exp(durs, tau_nom)

    lr_stat = 2.0 * (ll_libre - ll_h0)
    lr_stat = max(lr_stat, 0.0)
    p_valor = float(1.0 - stats.chi2.cdf(lr_stat, df=1))

    pasa = p_valor > 0.05

    return {

        "n_violaciones":       int(len(t_viol)),
        "duracion_media":      round(float(durs.mean()), 2),
        "b_weibull":           round(float(b_hat), 4),
        "lr_stat":             round(lr_stat, 4),
        "p_valor":             round(p_valor, 4),
        "pasa_independencia":  bool(pasa),
        "interpretacion_b":    (
            "agrupadas (riesgo)" if b_hat < 0.9
            else "dispersas (conservador)" if b_hat > 1.1
            else "aproximadamente independientes"
        ),

        # Array crudo para reporte (distribución de duraciones → fit Weibull visual)

        "duraciones":          durs.tolist(),
        "descripcion": (
            f"Ventana {ventana}d | τ={tau_col:.2f} | "
            f"b_Weibull={b_hat:.3f} | LR={lr_stat:.3f} | p={p_valor:.4f} | "
            f"{'✓ PASA independencia' if pasa else '✗ FALLA independencia'}"
        ),

    }
 


def backtest_pieza3_pit(
    df_sim:         pd.DataFrame,
    ventana:        int = 22,
    taus_disponibles: list[float] | None = None,
    submuestrear:   bool = True,
) -> dict:
    """
    Pieza 3: PIT (Probability Integral Transform) con test Anderson-Darling.

    Para cada origen t, aproxima F̂_t(y_realizado) interpolando entre los
    cuantiles simulados disponibles. Los PITs deben ser U[0,1] si el modelo
    está calibrado.

    Parámetros
    ----------
    submuestrear : si True, usa orígenes separados por la ventana para
                   el test formal (observaciones no solapadas).

    Devuelve dict con: pits (array), A2_stat, p_valor, pasa_uniformidad,
    descripcion (+ diagnóstico de la forma del histograma).
    """
    if taus_disponibles is None:
        taus_disponibles = [0.01, 0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95, 0.99]

    sub = df_sim[df_sim["ventana"] == ventana].copy()
    if len(sub) < 10:
        return {"error": "insuficientes observaciones"}

    # Pivot: rows=fecha_t, cols=tau, values=percentil_acum
    pivot = sub.pivot_table(index="fecha_t", columns="tau",
                            values="percentil_acum")
    pivot = pivot.sort_index()

    # Solo filas con todos los cuantiles y y_real disponible
    y_real = (sub.drop_duplicates("fecha_t")
              .set_index("fecha_t")["y_realizado_acum"]
              .sort_index())
    
    pivot  = pivot.loc[pivot.index.intersection(y_real.index)]
    y_real = y_real.loc[pivot.index]
    # taus_avail se calcula ANTES del dropna para basar la limpieza
    # solo en las columnas que realmente se van a usar — no en las 9
    # del default. pivot.dropna() sin args descartaba filas donde
    # CUALQUIER tau tuviera NaN, dejando len(pivot) < 5 con frecuencia.
    taus_avail = sorted(t for t in taus_disponibles if t in pivot.columns)
    if len(taus_avail) < 3:
        return {"error": "cuantiles o filas insuficientes para PIT"}
    pivot  = pivot[taus_avail].dropna()    # solo sobre columnas usadas
    y_real = y_real.loc[pivot.index].values
    if len(pivot) < 5:
        return {"error": "cuantiles o filas insuficientes para PIT"}
 
    q_mat = pivot[taus_avail].values  # shape (n_fechas, n_taus)
    n     = len(y_real)
    
    
    # PIT por interpolación lineal entre cuantiles disponibles
    pits = np.empty(n)
    for i in range(n):
        y_i = y_real[i]
        q_i = q_mat[i]
        if np.isnan(y_i) or np.any(np.isnan(q_i)):
            pits[i] = np.nan
            continue
        if y_i <= q_i[0]:
            pits[i] = taus_avail[0]
        elif y_i >= q_i[-1]:
            pits[i] = taus_avail[-1]
        else:
            pits[i] = float(np.interp(y_i, q_i, taus_avail))

    pits_clean = pits[~np.isnan(pits)]
    if len(pits_clean) < 5:
        return {"error": "insuficientes PITs válidos"}
     
    # Submuestreo para test formal (evita solapamiento)
    _MIN_PITS_AD = 20   # mínimo razonable para que el AD sea asintóticamente válido
    if submuestrear and len(pits_clean) > ventana:
        pits_test = pits_clean[::max(1, ventana)]
    else:
        pits_test = pits_clean
    # Guard: si el submuestreo dejó muy pocos puntos, usar todos
    if len(pits_test) < _MIN_PITS_AD:
        pits_test = pits_clean
 
    # Anderson-Darling test de uniformidad
    try:
        ad_stat, crit_vals, sig_levels = stats.anderson(pits_test, dist="uniform")
        sig_array = np.array([0.15, 0.10, 0.05, 0.025, 0.01])
        if ad_stat >= crit_vals[-1]:
            p_aprox = 0.005
        elif ad_stat <= crit_vals[0]:
            p_aprox = 0.20
        else:
            p_aprox = float(np.interp(ad_stat, crit_vals, sig_array))
            # idx_b eliminado — era dead code
    except Exception as _e_ad: 
        
        logger.debug(f"backtest_pieza3: fallo cálculo Anderson-Darling → "
                     f"{type(_e_ad).__name__}: {_e_ad}")
        ad_stat, p_aprox = np.nan, np.nan

    pasa = (not np.isnan(p_aprox)) and (p_aprox > 0.05)

    # Diagnóstico de la forma del histograma de PITs
    p25, p50, p75 = np.percentile(pits_clean, [25, 50, 75])
    pit_mean = float(pits_clean.mean())
    if pit_mean > 0.6:
        forma = "sesgado a 1 → realizado cae sistemáticamente en la cola superior (subest. riesgo)"
    elif pit_mean < 0.4:
        forma = "sesgado a 0 → realizado cae en la cola inferior (sobreest. riesgo)"
    elif p25 < 0.15 and p75 > 0.85:
        forma = "forma U → distribución demasiado angosta (sub-cobertura)"
    elif p25 > 0.30 and p75 < 0.70:
        forma = "forma campana → distribución demasiado ancha (sobre-cobertura)"
    else:
        forma = "aproximadamente uniforme → bien calibrado"

    return {
        "n_pits":          len(pits_clean),
        "n_pits_test":     len(pits_test),
        "pit_mean":        round(pit_mean, 4),
        "pit_p25":         round(p25, 4),
        "pit_p75":         round(p75, 4),
        "A2_stat":         round(float(ad_stat), 4) if not np.isnan(ad_stat) else None,
        "p_valor_aprox":   round(p_aprox, 4) if not np.isnan(p_aprox) else None,
        "pasa_uniformidad": bool(pasa),
        "forma_histograma": forma,
        "pits":            pits_clean,
        "descripcion": (
            f"Ventana {ventana}d | PIT mean={pit_mean:.3f} | "
            f"A²={ad_stat:.3f} | p≈{p_aprox:.4f} | "
            f"{'✓ PASA uniformidad' if pasa else '✗ FALLA uniformidad'} | "
            f"{forma}"
        ),
    }


def backtest_completo(
    df_sim:     pd.DataFrame,
    tau_col:    float = 0.05,
    ventanas:   list[int] | None = None,
    lag_nw:     int | None = None,
    taus_disp:  list[float] | None = None,
    return_raw: bool = False,
) -> "pd.DataFrame | tuple[pd.DataFrame, dict]":
    """
    Corre las tres piezas de backtest para cada ventana de plazo.
 
    Parámetros
    ----------
    return_raw : si True devuelve (df_resumen, datos_raw) donde datos_raw
                 contiene los arrays crudos necesarios para el reporte completo:
                   - "pits"        : {ventana: np.ndarray}
                   - "indicadores" : {ventana: {"fechas_t": list, "I": list}}
                   - "duraciones"  : {ventana: np.ndarray}
                 Si False (default) devuelve solo df_resumen — sin romper
                 código existente que llama sin return_raw.
    """
    if ventanas is None:
        ventanas = sorted(df_sim["ventana"].unique().tolist())
    rows        = []
    raw_pits    = {}
    raw_indic   = {}
    raw_durs    = {}
 
    for v in ventanas:
        r1 = backtest_pieza1_violaciones(df_sim, tau_col, v,
                                         lag_nw=lag_nw if lag_nw else v)
        r2 = backtest_pieza2_duraciones(df_sim, tau_col, v)
        r3 = backtest_pieza3_pit(df_sim, v, taus_disponibles=taus_disp)
 
        # ── Arrays crudos ───────────────────────────────────────────────────
        if "pits" in r3 and r3["pits"] is not None:
            raw_pits[v]  = np.asarray(r3["pits"])
        if "I_indicators" in r1 and r1["I_indicators"] is not None:
            raw_indic[v] = {
                "fechas_t": r1.get("fechas_t", []),
                "I":        r1["I_indicators"],
            }
        if "duraciones" in r2 and r2["duraciones"] is not None:
            raw_durs[v]  = np.asarray(r2["duraciones"])
 
        rows.append({
            "ventana":          v,
            # ── Pieza 1 — violaciones Newey-West ─────────────────────────────
            "n_obs":            r1.get("n"),
            "lag_nw":           r1.get("lag_nw"),
            "tasa_empirica":    r1.get("tasa_empirica"),
            "ic95_lo":          r1.get("ic95_lo"),
            "ic95_hi":          r1.get("ic95_hi"),
            "p1_pasa":          r1.get("pasa"),
            "p1_descripcion":   r1.get("descripcion"),
            # ── Pieza 2 — duraciones Weibull ──────────────────────────────────
            "n_violaciones":    r2.get("n_violaciones"),
            "duracion_media":   r2.get("duracion_media"),
            "b_weibull":        r2.get("b_weibull"),
            "lr_stat":          r2.get("lr_stat"),
            "lr_p_valor":       r2.get("p_valor"),
            "p2_independencia": r2.get("pasa_independencia"),
            "interp_b":         r2.get("interpretacion_b"),
            "p2_descripcion":   r2.get("descripcion"),
            # ── Pieza 3 — PIT Anderson-Darling ───────────────────────────────
            "n_pits":           r3.get("n_pits"),
            "n_pits_test":      r3.get("n_pits_test"),
            "pit_mean":         r3.get("pit_mean"),
            "pit_p25":          r3.get("pit_p25"),
            "pit_p75":          r3.get("pit_p75"),
            "A2_stat":          r3.get("A2_stat"),
            "AD_p_valor":       r3.get("p_valor_aprox"),
            "p3_uniformidad":   r3.get("pasa_uniformidad"),
            "forma_pit":        r3.get("forma_histograma"),
            "p3_descripcion":   r3.get("descripcion"),
        })
 
    df_out = pd.DataFrame(rows)
    if return_raw:
        return df_out, {"pits": raw_pits, "indicadores": raw_indic,
                        "duraciones": raw_durs}
    return df_out



def _worker_z_fila(args: tuple) -> float:
    """
    Worker de multiprocessing para _construir_serie_z. Función de MÓDULO
    (no closure) por la misma razón que _worker_fitear_uno: picklable en
    Windows (spawn).
    """
    y, q_vals, taus = args
    dist = fitear_skewt(list(q_vals), list(taus))
    u = float(dist.cdf(np.array([y]))[0])
    return float(stats.norm.ppf(np.clip(u, 1e-6, 1 - 1e-6)))


def _pit_un_punto(y: float, q_vals: np.ndarray, taus: np.ndarray) -> float:
    """
    PIT vía la SplitT (skew-t completa) ajustada a los cuantiles predichos —
    asimetría y colas con grados de libertad finitos, deliberadamente más
    flexible que una aproximación cerrada. Costosa por fila (~0.2s,
    optimización no lineal); por eso _construir_serie_z la paraleliza con
    multiprocessing en vez de llamar esta función en un loop serial.

    Por qué no interpolación lineal con clip (el método original más viejo):
    un dato fuera de [Q01,Q99] se clavaba en PIT=0.01/0.99 sin importar cuán
    extremo fuera — pierde toda la información de magnitud en la cola, que es
    donde más importa para el régimen severo. La skew-t extrapola de forma
    continua y con la asimetría/curtosis que el ajuste encuentre.
    """
    dist = fitear_skewt(list(q_vals), list(taus))
    return float(dist.cdf(np.array([y]))[0])


def _construir_serie_z(
    df_sub:  pd.DataFrame,
    col_q:   list[str],
    taus_arr: np.ndarray,
    n_jobs:  int = -1,
) -> np.ndarray:
    """
    Calcula z_t = Φ⁻¹(PIT_t) para cada fila de df_sub, fiteando una skew-t
    completa por fila (vía _pit_un_punto / fitear_skewt) y paralelizando con
    multiprocessing — cada fit es ~0.2s (optimización no lineal); sobre series
    de miles de días el cómputo serial es impracticable (minutos).

    n_jobs : -1 usa todos los cores disponibles (os.cpu_count()); 1 fuerza
             ejecución serial. Con <50 filas siempre corre serial (el
             overhead de levantar procesos no se justifica).
    """
    tareas = [
        (float(row.y_realizado),
         tuple(getattr(row, c) for c in col_q),
         tuple(taus_arr.tolist()))
        for row in df_sub.itertuples(index=False)
    ]
    total = len(tareas)
    n_procesos = os.cpu_count() if n_jobs == -1 else n_jobs

    if n_jobs == 1 or total < 50:
        resultados = [_worker_z_fila(t) for t in tareas]
    else:
        logger.info(f"  [step006] Calculando {total} PIT/z (skew-t, "
                   f"n_jobs={n_procesos})...")
        try:
            with multiprocessing.Pool(processes=n_procesos) as pool:
                chunksize = max(1, total // (n_procesos * 4))
                resultados = pool.map(_worker_z_fila, tareas, chunksize=chunksize)
        except Exception as e:
            logger.warning(f"  [step006] multiprocessing falló ({e}); "
                          f"usando ejecución serial.")
            resultados = [_worker_z_fila(t) for t in tareas]

    return np.array(resultados)


def estimar_rho_por_regimen(
    df_preds:      pd.DataFrame,
    h_referencia:  int = 1,
    taus:          list[float] | None = None,
    max_gap_dias:  int = 4,
    rho_default:   float = 0.3,
    n_jobs:        int = -1,
) -> dict[int, float]:
    """
    Estima ρ_s (correlación AR(1) de la cópula) POR RÉGIMEN, a partir de los
    residuos reales — cierra el pendiente "estimar ρ_s por régimen (autocorr.
    de residuos de XGBoost condicionada al estado HMM)".

    Método
    ------
    1. Toma SOLO las filas con h == h_referencia (por defecto h=1, un paso
       adelante). Por construcción del problema, la predicción a horizonte h
       desde el origen t y la predicción a horizonte h+1 desde el origen t-1
       caen en el MISMO día calendario realizado — así que la serie de
       residuos a h fijo, ordenada por fecha, ES la serie temporal de
       sorpresas día a día (no hay necesidad de usar h=1..75 de un solo
       origen: es la misma información).
    2. PIT vía SplitT: u_t = F̂_t(y_realizado_t) usando la skew-t ajustada a
       los cuantiles de ESE día (ver _pit_un_punto — extrapola colas en vez
       de clavarse en Q01/Q99). z_t = Φ⁻¹(u_t) — normaliza el residuo a
       escala N(0,1), consistente con la recursión gaussiana de la cópula.
       Paralelizado con multiprocessing (ver _construir_serie_z) porque cada
       fit es ~0.2s y la serie puede tener miles de días.
    3. Para cada régimen s, calcula la autocorrelación lag-1 de z_t restringida
       a pares (t-1, t) donde: (a) el día t está clasificado en régimen s
       (mismo criterio que la simulación, que usa el régimen del paso DESTINO
       k, no el de origen), y (b) la separación calendario entre t-1 y t es
       ≤ max_gap_dias (evita correlacionar across de huecos entre folds).

    Parámetros
    ----------
    df_preds      : df_preds con columna 'regimen_hmm' ya mergeada (la que
                    guarda step005_walk_forward_cv_4.py).
    h_referencia  : horizonte (lead time) del pronóstico usado para construir
                    la serie diaria de sorpresas — NO es el rezago de la
                    autocorrelación (ese está fijo en 1 fila más abajo, ver
                    z_prev/z_cur). h_referencia responde "¿con cuánta
                    anticipación se hizo el pronóstico que comparo contra lo
                    realizado?"; el rezago responde "¿comparo cada día contra
                    el inmediatamente anterior, o contra uno más lejano?".
                    Son decisiones independientes que aquí coinciden en valor
                    por una razón distinta a "elegir el rezago": h=1 no
                    existe en datos donde T+1 ya se conoce con certeza (no es
                    una predicción), así que el horizonte mínimo con
                    incertidumbre genuina (p.ej. h=2 con convención T+2) es,
                    a la vez, el pronóstico más fresco disponible — la mejor
                    aproximación al primer paso real que se va a simular en
                    pipeline_simulacion, no un sustituto de segunda opción.
                    Cambiar h_referencia (2 vs 3, etc.) SÍ puede cambiar el
                    ρ_s estimado, porque mide la sorpresa contra pronósticos
                    con distinta anticipación — no es indiferente a esa
                    elección, aunque el rezago entre observaciones siga
                    siendo 1 día hábil en cualquier caso (def. 1).
    max_gap_dias  : separación calendario máxima entre días consecutivos
                    para que el par cuente en la autocorrelación.
    rho_default   : valor a devolver para un régimen sin suficientes
                    observaciones para estimar (con aviso).
    n_jobs        : procesos paralelos para el cálculo de PIT/z (ver
                    _construir_serie_z). -1 = todos los cores; 1 = serial.

    Devuelve
    --------
    dict {estado: ρ_s} para TODOS los estados presentes en la columna
    'regimen_hmm' de df_preds completo (2 o 3, según N_ESTADOS) — no solo
    los que aparecen en el subconjunto filtrado por h_referencia. Un régimen
    sin pares suficientes recibe rho_default explícitamente, con aviso.
    """
    if taus is None:
        taus = TAUS_STD
    if "regimen_hmm" not in df_preds.columns:
        raise ValueError("df_preds no tiene columna 'regimen_hmm' — "
                        "¿corriste step005_walk_forward_cv_4.py con "
                        "USAR_FEATURE_REGIMEN=True?")

    col_q = [f"q{int(t*100):02d}" for t in taus]
    sub = df_preds[df_preds["h"] == h_referencia].copy()
    if sub.empty:
        h_disponibles = sorted(df_preds["h"].unique().tolist())
        raise ValueError(
            f"h_referencia={h_referencia} no existe en df_preds — horizontes "
            f"disponibles: {h_disponibles[:10]}{'...' if len(h_disponibles) > 10 else ''}. "
            f"Ajusta h_referencia al horizonte mínimo real (p.ej. si tu grid "
            f"arranca en h=2 por convención T+2, usa h_referencia=2).")
    sub["fecha_t"] = pd.to_datetime(sub["fecha_t"])
    sub = sub.dropna(subset=["y_realizado", "regimen_hmm"] + col_q)
    sub = sub.sort_values("fecha_t").reset_index(drop=True)

    if len(sub) < 30:
        logger.warning(f"  [step006] solo {len(sub)} filas con h={h_referencia} "
                       f"para estimar ρ_s — resultado poco confiable.")

    taus_arr = np.array(taus)
    z = _construir_serie_z(sub, col_q, taus_arr, n_jobs=n_jobs)

    fechas   = sub["fecha_t"].values
    regimen  = sub["regimen_hmm"].values.astype(int)
    gap_dias = np.diff(fechas).astype("timedelta64[D]").astype(int)

    z_prev, z_cur, regimen_cur = z[:-1], z[1:], regimen[1:]
    valido = gap_dias <= max_gap_dias

    # Iterar sobre TODOS los regímenes presentes en df_preds completo — no
    # solo los que aparecen en el subconjunto filtrado por h_referencia.
    # Sin esto: si un régimen (p.ej. "severo", el más raro) no aparece por
    # azar en esta ventana específica, el dict devuelto queda incompleto, y
    # simular_un_path usa rho_por_regimen.get(k, 0.0) — es decir, ese
    # régimen recibe rho=0.0 (sin persistencia) en vez de rho_default, SIN
    # ningún aviso de que pasó. 2 o 3 estados, según N_ESTADOS con el que
    # se corrió step005_validar_hmm*.py — nunca se asume un número fijo.
    _regimenes_todos = sorted(set(
        df_preds["regimen_hmm"].dropna().astype(int).unique().tolist()))

    rho_por_regimen: dict[int, float] = {}
    for s in _regimenes_todos:
        mask = valido & (regimen_cur == s)
        n_validos = int(mask.sum())
        if n_validos < 30:
            logger.warning(f"  [step006] régimen {s}: solo {n_validos} pares "
                           f"válidos para autocorr. — usando ρ_default="
                           f"{rho_default}")
            rho_por_regimen[s] = rho_default
            continue
        rho = float(np.corrcoef(z_prev[mask], z_cur[mask])[0, 1])
        rho = float(np.clip(rho, -0.95, 0.95))   # evita |ρ|≈1 (degenera la recursión)
        rho_por_regimen[s] = rho
        logger.info(f"  [step006] ρ_s régimen {s}: {rho:.3f}  (n={n_validos})")

    return rho_por_regimen



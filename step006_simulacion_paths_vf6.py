# PARTE 3 — Simulación de régimen (cadena de Markov del HMM)
# ══════════════════════════════════════════════════════════════════════════════

def simular_regimen_path(
    estado_inicial: int,
    matriz_transicion: np.ndarray,
    n_pasos: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    Simula una secuencia de estados de régimen para n_pasos horizontes.
    matriz_transicion[i, j] = P(S_{t+1}=j | S_t=i).
    Devuelve array de shape (n_pasos,) con int de 0 a n_estados-1.
    """
    n_estados = matriz_transicion.shape[0]
    estados   = np.empty(n_pasos, dtype=int)
    estados[0] = estado_inicial
    umbrales   = np.cumsum(matriz_transicion, axis=1)  # pre-computa CDF por fila

    for k in range(1, n_pasos):
        v = rng.random()
        row = umbrales[estados[k - 1]]
        estados[k] = int(np.searchsorted(row, v, side="right"))
        estados[k] = min(estados[k], n_estados - 1)  # seguridad

    return estados



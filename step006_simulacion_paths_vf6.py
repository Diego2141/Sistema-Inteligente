def _worker_fitear_uno(args: tuple) -> tuple:
    """
    Worker de multiprocessing para fitear_distribuciones_por_horizonte.
    Debe ser función de MÓDULO (no closure/lambda local) para que
    multiprocessing pueda picklearla y enviarla a los procesos hijos en
    Windows (spawn) — una función anidada o un lambda no son picklables ahí.
    """
    key, q_vals, taus = args
    q_arr = np.asarray(q_vals, dtype=float)

    # 1. Verificar NaN
    if np.any(np.isnan(q_arr)):
        idx_med = len(taus) // 2
        loc = float(q_arr[idx_med]) if not np.isnan(q_arr[idx_med]) else 0.0
        logger.debug(f"  [fitear] {key}: cuantiles con NaN — fallback AzzaliniT simétrica")
        return key, AzzaliniT(loc, 1.0, 0.0, 6.0)

    # 2. Verificar monotonicidad estricta
    # XGBoost puede producir Q05 > Q50 con pocos datos de entrenamiento en un fold.
    # Si los cuantiles no son estrictamente crecientes, el fit falla o produce
    # distribuciones degeneradas sin ningún error visible.
    if np.any(np.diff(q_arr) <= 0):
        # Forzar monotonicidad mínima por jitter antes de fitear
        q_fixed = q_arr.copy()
        eps = max(abs(q_arr.max() - q_arr.min()) * 1e-4, 1.0)
        for i in range(1, len(q_fixed)):
            if q_fixed[i] <= q_fixed[i-1]:
                q_fixed[i] = q_fixed[i-1] + eps
        logger.warning(f"  [fitear] {key}: cuantiles no monótonos — "
                       f"original={q_arr.round(0).tolist()} "
                       f"corregido={q_fixed.round(0).tolist()}")
        q_vals = q_fixed.tolist()

    return key, fitear_skewt(q_vals, taus)


def fitear_distribuciones_por_horizonte(
    df_preds: pd.DataFrame,
    taus: list[float] | None = None,
    n_jobs: int = -1,
) -> dict[tuple, AzzaliniT | SplitT]:
    """
    Para cada combinación única (fecha_t, h) en df_preds, fitea una SplitT
    a los cuantiles predichos (skew-t completa: asimetría + colas con grados
    de libertad finitos — deliberadamente más flexible y más costosa que una
    aproximación cerrada).

    Cada fit es una optimización no lineal (~0.2s) — sobre miles de filas
    (orígenes × horizontes) el cómputo serial es impracticable, por eso se
    paraleliza con multiprocessing.

    Columnas requeridas: fecha_t, h, q01, q05, q50, q95, q99
    (o las que correspondan a los taus indicados).

    Parámetros
    ----------
    n_jobs : -1 usa todos los cores disponibles (os.cpu_count()); 1 fuerza
             ejecución serial (depuración, o entornos sin soporte de
             multiprocessing). Con <50 filas siempre corre serial (el
             overhead de levantar procesos no se justifica).

    Devuelve
    --------
    dict  {(fecha_t, h): SplitT}
    """
    if taus is None:
        taus = TAUS_STD

    col_map = {tau: f"q{int(tau*100):02d}" for tau in taus}
    missing = [c for c in col_map.values() if c not in df_preds.columns]
    if missing:
        raise ValueError(f"Columnas faltantes en df_preds: {missing}")

    # Normalizar fecha_t a pd.Timestamp y h a Python int en la clave,
    # para que el hash del dict sea siempre consistente con el lookup en
    # simular_un_path — np.int64 y int tienen el mismo valor pero pueden
    # diferir en comportamiento de hash en versiones antiguas de CPython,
    # y Timestamp vs str claramente difieren.
    tareas = []
    for row in df_preds.itertuples(index=False):
        key = (pd.Timestamp(row.fecha_t), int(row.h))
        q_vals = [getattr(row, col_map[t]) for t in taus]
        tareas.append((key, q_vals, list(taus)))

    total = len(tareas)
    n_procesos = os.cpu_count() if n_jobs == -1 else n_jobs
    logger.info(f"    [step006] Fiteando {total} distribuciones split-t "
               f"(n_jobs={n_procesos if (n_jobs != 1 and total >= 50) else 1})...")

    if n_jobs == 1 or total < 50:
        resultados = [_worker_fitear_uno(t) for t in tareas]
    else:
        try:
            with multiprocessing.Pool(processes=n_procesos) as pool:
                chunksize = max(1, total // (n_procesos * 4))
                resultados = pool.map(_worker_fitear_uno, tareas, chunksize=chunksize)
        except Exception as e:
            logger.warning(f"    [step006] multiprocessing falló ({e}); "
                          f"usando ejecución serial.")
            resultados = [_worker_fitear_uno(t) for t in tareas]

    distribuciones = dict(resultados)
    logger.info(f"    [step006] {len(distribuciones)} distribuciones fiteadas")
    return distribuciones



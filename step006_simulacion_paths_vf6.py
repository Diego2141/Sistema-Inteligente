# PARTE 1 — Azzalini-Capitanio skew-t (AC2003)
# ══════════════════════════════════════════════════════════════════════════════
#
# Referencia: Azzalini, A. & Capitanio, A. (2003). "Distributions generated by
# perturbation of symmetry with emphasis on a multivariate skew-t distribution."
# Journal of the Royal Statistical Society B, 65(2), 367-389.
#
# Parámetros: xi (localización), omega (escala > 0), alpha (forma ∈ ℝ), nu (df > 2)
#
# PDF:  f(x; xi, omega, alpha, nu) =
#         (2/omega) · t_nu((x-xi)/omega) · T_{nu+1}(alpha · z · sqrt((nu+1)/(nu+z²)))
#
# donde z = (x-xi)/omega, t_nu = PDF de t-Student con nu df,
#       T_{nu+1} = CDF de t-Student con nu+1 df  ← clave AC2003 (no nu).
#
# CDF: No tiene forma cerrada. Se calcula vía cuadratura Gauss-Legendre con
#      cambio de variable u = t/(1+|t|) que compacta ℝ en (-1,1), permitiendo
#      nodos fijos y pesos fijos precomputados para integración vectorizada.
#
# PPF: Sin forma cerrada. Se precalcula una malla de 200 cuantiles con Newton
#      (usando el PDF analítico como derivada), y luego se interpola linealmente.
#      La malla se construye una sola vez por objeto (lazy o eagerly en fitear_skewt).

# Nodos y pesos GL de grado 80 precomputados a nivel de módulo (thread-safe,
# inmutables). Orden 80 garantiza ~15 dígitos de precisión para funciones suaves.
_GL_NODES, _GL_WEIGHTS = np.polynomial.legendre.leggauss(80)


class AzzaliniT:
    """
    Distribución skew-t de Azzalini & Capitanio (2003).

    Parámetros
    ----------
    xi    : localización
    omega : escala (> 0)
    alpha : forma/asimetría (ℝ; alpha=0 → t-Student simétrica)
    nu    : grados de libertad (> 2 para varianza finita)
    """

    _PPF_N     = 200          # puntos en la malla de PPF
    _PPF_U_MIN = 1e-4         # límite inferior de la malla (evita divergencia)
    _PPF_U_MAX = 1.0 - 1e-4  # límite superior
    _PPF_ITER  = 20           # máximo de iteraciones Newton
    _PPF_TOL   = 1e-9         # tolerancia de convergencia Newton

    __slots__ = ("xi", "omega", "alpha", "nu", "_ppf_u", "_ppf_x")

    def __init__(self, xi: float, omega: float, alpha: float, nu: float):
        self.xi    = float(xi)
        self.omega = max(float(omega), 1e-12)
        self.alpha = float(alpha)
        self.nu    = max(float(nu), 2.01)
        self._ppf_u: np.ndarray | None = None
        self._ppf_x: np.ndarray | None = None

    # ── PDF analítico ─────────────────────────────────────────────────────────

    def _pdf_std(self, z: np.ndarray) -> np.ndarray:
        """
        PDF estandarizada (xi=0, omega=1) en un array de puntos z.
        Implementa exactamente la ecuación (4) de AC2003:
          2 · t_nu(z) · T_{nu+1}(alpha · z · sqrt((nu+1)/(nu+z²)))
        Nota: T_{nu+1} usa nu+1 grados de libertad — detalle crítico de AC2003.
        """
        t_pdf = stats.t.pdf(z, df=self.nu)
        with np.errstate(invalid="ignore", divide="ignore"):
            denom = np.maximum(self.nu + z ** 2, 1e-300)
            inner = self.alpha * z * np.sqrt((self.nu + 1.0) / denom)
        t_cdf = stats.t.cdf(inner, df=self.nu + 1.0)   # nu+1, no nu
        return 2.0 * t_pdf * t_cdf

    def pdf(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return self._pdf_std((x - self.xi) / self.omega) / self.omega

    # ── CDF vía Gauss-Legendre vectorizado ────────────────────────────────────

    def _cdf_batch(self, z_arr: np.ndarray) -> np.ndarray:
        """
        CDF estandarizada en un array de puntos z_arr, calculada simultáneamente.

        Cambio de variable: u = t/(1+|t|) compacta ℝ → (-1,1).
          Inversa: t = u/(1-|u|)
          Jacobiano: dt/du = 1/(1-|u|)²
        Integración GL en [-1, u_upper] donde u_upper = z/(1+|z|).

        Vectoriza sobre z_arr: construye tensor (n_z × n_GL) en un solo bloque
        numpy, evitando el loop Python sobre puntos z. Esencial para que el
        cálculo de la malla PPF sea viable con decenas de miles de objetos.
        """
        n_z  = len(z_arr)
        n_gl = len(_GL_NODES)

        u_up = np.clip(z_arr / (1.0 + np.abs(z_arr)), -1.0 + 1e-9, 1.0 - 1e-9)

        hw  = (u_up + 1.0) * 0.5        # (n_z,)
        mid = (u_up - 1.0) * 0.5        # (n_z,)

        # Nodos GL mapeados a [a_i, b_i] para cada z_i — tensor (n_z, n_gl)
        u_pts   = hw[:, None] * _GL_NODES[None, :] + mid[:, None]
        abs_u   = np.minimum(np.abs(u_pts), 1.0 - 1e-12)
        t_pts   = u_pts / (1.0 - abs_u)
        jac     = 1.0 / (1.0 - abs_u) ** 2

        # Integrando = 2 · t_nu(t) · T_{nu+1}(alpha·t·sqrt((nu+1)/(nu+t²))) · jac
        flat    = t_pts.ravel()
        t_pdf_v = stats.t.pdf(flat, df=self.nu).reshape(n_z, n_gl)
        with np.errstate(invalid="ignore", divide="ignore"):
            inner_v = (self.alpha * t_pts *
                       np.sqrt((self.nu + 1.0) /
                                np.maximum(self.nu + t_pts ** 2, 1e-300)))
        t_cdf_v = stats.t.cdf(inner_v.ravel(), df=self.nu + 1.0).reshape(n_z, n_gl)

        integrand = 2.0 * t_pdf_v * t_cdf_v * jac      # (n_z, n_gl)
        result    = hw * np.einsum("j,ij->i", _GL_WEIGHTS, integrand)
        return np.clip(result, 0.0, 1.0)

    def cdf(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return self._cdf_batch((x - self.xi) / self.omega)

    # ── PPF vía malla precomputada ────────────────────────────────────────────

    def _build_ppf_grid(self) -> None:
        """
        Construye la malla PPF usando brentq — más robusto que Newton para
        alpha extremos donde Newton diverge al cruzar regiones de PDF≈0.

        Bracket: rango de la t-Student simétrica (misma nu) ampliado por la
        asimetría de la AC — para alpha>0 la masa va a la derecha (hi más ancho);
        para alpha<0 a la izquierda (lo más ancho). Factor 12*|alpha| garantiza
        cubrir la distribución incluso para alpha=±15.
        """
        from scipy.optimize import brentq as _brentq

        u_grid = np.linspace(self._PPF_U_MIN, self._PPF_U_MAX, self._PPF_N)

        # Bracket ancho ajustado por dirección de asimetría
        t_lo = float(stats.t.ppf(1e-8, df=self.nu))
        t_hi = float(stats.t.ppf(1.0 - 1e-8, df=self.nu))
        skew_shift = float(np.clip(self.alpha, -15.0, 15.0))
        lo = (t_lo + min(skew_shift, 0) * 12.0) * self.omega + self.xi
        hi = (t_hi + max(skew_shift, 0) * 12.0) * self.omega + self.xi

        x_grid = np.empty(self._PPF_N)
        for i, u_i in enumerate(u_grid):
            try:
                x_grid[i] = _brentq(
                    lambda x: float(self._cdf_batch(
                        np.array([(x - self.xi) / self.omega]))[0]) - u_i,
                    lo, hi,
                    xtol=self._PPF_TOL, maxiter=self._PPF_ITER * 3,
                )
            except Exception as _e_brentq:
                logger.debug(
                    f"AzzaliniT._build_ppf_grid: brentq falló en u={u_i:.4f} "
                    f"(xi={self.xi:.3g}, omega={self.omega:.3g}, "
                    f"alpha={self.alpha:.3g}, nu={self.nu:.1f}) → "
                    f"{type(_e_brentq).__name__}: {_e_brentq} — usando fallback t-simétrica"
                )
                x_grid[i] = float(stats.t.ppf(u_i, df=self.nu)) * self.omega + self.xi

        # Garantizar monotonicidad estricta (brentq puede producir empates en extremos)
        for i in range(1, len(x_grid)):
            if x_grid[i] <= x_grid[i - 1]:
                x_grid[i] = x_grid[i - 1] + 1e-10

        self._ppf_u = u_grid
        self._ppf_x = x_grid

    def ppf(self, u) -> np.ndarray:
        """
        Función cuantil vía interpolación lineal sobre la malla precomputada.
        Construye la malla en la primera llamada si no existe (lazy init).
        En fitear_skewt se construye eagerly para que sea thread-safe durante
        el multiprocessing del pipeline.
        """
        if self._ppf_u is None:
            self._build_ppf_grid()
        u = np.atleast_1d(np.asarray(u, dtype=float))
        return np.interp(np.clip(u, self._ppf_u[0], self._ppf_u[-1]),
                         self._ppf_u, self._ppf_x)


# ─────────────────────────────────────────────────────────────────────────────
# SplitT — Fernández & Steel (1998) two-piece t
# ─────────────────────────────────────────────────────────────────────────────
# Usada como FALLBACK cuando el optimizador AC2003 no converge.
# Ventajas sobre la t-Student simétrica como fallback:
#   · Captura asimetría vía scale_l ≠ scale_r — la t simétrica fuerza
#     alpha=0 que puede ser una mala aproximación a cuantiles asimétricos.
#   · CDF y PPF son ANALÍTICOS — sin grid PPF, sin brentq, sin Newton.
#     Es inmune a los problemas de convergencia del optimizador AC2003.
#   · Usada por el Bank of England en fan charts de inflación y por varios
#     bancos centrales para distribuciones predictivas de variables financieras.
# Referencia: Fernández, C. & Steel, M.F.J. (1998). "On Bayesian modeling of
# fat tails and skewness." JASA 93(441), 359-371.

class SplitT:
    """
    Distribución t de dos piezas (Fernández & Steel, 1998).

    CDF:  F(x) = 2·p_L · T_df((x-loc)/scale_l)           para x ≤ loc
          F(x) = 1 − 2·p_R · T_df((loc-x)/scale_r)        para x > loc

    PPF:  Q(u) = loc + scale_l · t_df.ppf(u/(2·p_L))      para u ≤ p_L
          Q(u) = loc − scale_r · t_df.ppf((1-u)/(2·p_R))  para u > p_L

    donde p_L = scale_l/(scale_l+scale_r),  T_df = CDF t-Student con df grados.
    CDF y PPF completamente analíticos — sin optimización numérica adicional.
    """
    __slots__ = ("loc", "scale_l", "scale_r", "df", "_p_l", "_p_r")

    def __init__(self, loc: float, scale_l: float, scale_r: float, df: float):
        self.loc     = float(loc)
        self.scale_l = max(float(scale_l), 1e-9)
        self.scale_r = max(float(scale_r), 1e-9)
        self.df      = max(float(df), 2.01)
        self._p_l    = self.scale_l / (self.scale_l + self.scale_r)
        self._p_r    = self.scale_r / (self.scale_l + self.scale_r)

    def ppf(self, u) -> np.ndarray:
        u   = np.atleast_1d(np.asarray(u, dtype=float))
        out = np.empty_like(u)
        left  = u <= self._p_l
        right = ~left
        if left.any():
            out[left] = (self.loc
                         + self.scale_l
                         * stats.t.ppf(u[left] / (2.0 * self._p_l), self.df))
        if right.any():
            out[right] = (self.loc
                          - self.scale_r
                          * stats.t.ppf((1.0 - u[right]) / (2.0 * self._p_r),
                                        self.df))
        return out

    def cdf(self, x) -> np.ndarray:
        x   = np.atleast_1d(np.asarray(x, dtype=float))
        out = np.empty_like(x)
        left  = x <= self.loc
        right = ~left
        if left.any():
            out[left] = 2.0 * self._p_l * stats.t.cdf(
                (x[left] - self.loc) / self.scale_l, self.df)
        if right.any():
            out[right] = 1.0 - 2.0 * self._p_r * stats.t.cdf(
                (self.loc - x[right]) / self.scale_r, self.df)
        return out

class PchipGPD:
    """
    Distribución HÍBRIDA: cuerpo PCHIP + colas Pareto Generalizada (GPD).

    Motivación (ver diagnóstico de fit sobre 35.372 filas): el ajuste
    paramétrico acierta en Q01/Q99 (1.36% y 2.15% fuera de umbral) pero falla
    en Q05/Q95 (22.2% y 32.2%) — la forma paramétrica no puede satisfacer
    centro y ambas colas a la vez con 7 puntos. Este híbrido separa las
    responsabilidades en vez de pelear contra esa limitación:

      cuerpo [Q05, Q95] → PCHIP sobre los cuantiles observados. Interpola,
                          no aproxima: error CERO en cada nodo. Q05/Q95/Q50
                          quedan exactos por construcción. PCHIP (no spline
                          cúbico normal) porque PRESERVA MONOTONÍA — en una
                          CDF, un overshoot implicaría densidad negativa.

      colas             → GPD, con dos parámetros:
                          ξ (forma)  = 1/ν, HEREDADO del fit paramétrico.
                                       Resultado clásico de EVT: las colas
                                       de una t con ν g.l. decaen como
                                       potencia de exponente ν, y la GPD que
                                       las aproxima tiene forma 1/ν. Vale
                                       igual para AzzaliniT y SplitT (ambas
                                       heredan las colas de la t).
                          β (escala) = DESPEJADO para que la GPD pase
                                       exactamente por Q99 (o Q01). Forma
                                       cerrada, sin optimización.

    Continuidad: como β se calibra exigiendo F(Q99)=0.99, la CDF es continua
    en el umbral por construcción — no hay salto entre cuerpo y cola. En un
    híbrido esto suele ser la parte molesta; aquí sale gratis.

    ⚠ ξ = 1/ν es el índice de cola ASINTÓTICO (x→∞). En Q99 puede que aún no
      se esté en régimen asintótico, pero como β se calibra localmente contra
      Q99, la GPD acierta ahí por construcción: ξ solo gobierna cómo
      EXTRAPOLA más allá del último cuantil observado.
    """
    __slots__ = ("_q", "_taus", "_ppf_body", "_grid_u", "_grid_x",
                 "_u_l", "_tau_l", "_beta_l", "_u_r", "_tau_r", "_beta_r",
                 "xi_tail", "nu_origen", "familia_origen")

    def __init__(self, q_vals, taus, nu: float,
                 tau_umbral_izq: float | None = None, tau_ancla_izq: float | None = None,
                 tau_umbral_der: float | None = None, tau_ancla_der: float | None = None,
                 familia_origen: str = "?"):
        from scipy.interpolate import PchipInterpolator

        q    = np.asarray(q_vals, dtype=float)
        taus = np.asarray(taus,   dtype=float)
        orden = np.argsort(taus)
        self._q, self._taus = q[orden], taus[orden]

        # ── Umbrales y anclas: ADAPTATIVOS al conjunto de taus recibido ──────
        # Regla: ancla = tau más extremo de cada lado; umbral = el siguiente.
        # Así el cuerpo PCHIP cubre [tau_2, tau_{n-1}] y TODOS los cuantiles
        # interiores quedan exactos por interpolación, mientras el más extremo
        # de cada cola queda exacto por la calibración de β.
        #
        # ⚠ Con umbrales FIJOS (0.05/0.95) y un set rico de taus, los cuantiles
        #   intermedios de cola (p.ej. 0.005, 0.025, 0.975, 0.995 en el set de
        #   17) caerían dentro de la región GPD, donde solo hay UNA ancla por
        #   lado: quedarían sin garantía de exactitud. Medido en ese caso:
        #   error 1.16e-03 frente a ~1e-7 con umbrales adaptativos — es decir,
        #   el diseño desperdiciaba justamente los cuantiles de cola que más
        #   cuesta predecir. La regla adaptativa lo corrige y hace que el
        #   esquema escale a 5, 7, 13 o 17 taus sin cambios.
        if len(self._taus) < 4:
            raise ValueError(f"PchipGPD requiere al menos 4 cuantiles "
                            f"(2 por cola); recibidos {len(self._taus)}")
        _ancla_izq  = float(self._taus[0])  if tau_ancla_izq  is None else float(tau_ancla_izq)
        _umbral_izq = float(self._taus[1])  if tau_umbral_izq is None else float(tau_umbral_izq)
        _ancla_der  = float(self._taus[-1]) if tau_ancla_der  is None else float(tau_ancla_der)
        _umbral_der = float(self._taus[-2]) if tau_umbral_der is None else float(tau_umbral_der)

        # ξ heredado del fit paramétrico, con clip conservador (ver GPD_XI_MAX)
        self.nu_origen      = float(nu)
        self.familia_origen = str(familia_origen)
        self.xi_tail = float(np.clip(1.0 / max(float(nu), 1e-9),
                                     GPD_XI_MIN, GPD_XI_MAX))

        # Cuerpo: PCHIP como PPF (definición primaria) + su inversa numérica.
        #
        # ⚠ NO se usan dos PchipInterpolator independientes (uno x→F y otro
        #   F→x): NO son inversos exactos — coinciden en los nodos pero
        #   divergen entre ellos (medido: hasta 2.4e-2 de discrepancia).
        #   Eso rompería la coherencia del pipeline, porque la simulación usa
        #   ppf() y el backtest usa cdf(): si no son inversas, el PIT de los
        #   paths simulados no sale uniforme y el backtest mide mal.
        #   Solución: ppf es la definición (PCHIP puro, y es el camino
        #   caliente de la simulación), y cdf se obtiene interpolando sobre
        #   una malla densa generada por ppf → inversa exacta por construcción.
        self._ppf_body = PchipInterpolator(self._taus, self._q, extrapolate=False)
        # La malla NO se materializa aquí: son 32KB por objeto, y el pipeline
        # mantiene ~35k distribuciones en memoria (1.17 GB vs 0.01 GB del
        # paramétrico). Se construye on-demand en el primer cdf() y se excluye
        # del pickle (ver __getstate__), así el envío a los workers de
        # multiprocessing viaja ligero.
        self._grid_u = None
        self._grid_x = None

        # Umbrales y anclas
        self._tau_l = _umbral_izq
        self._tau_r = _umbral_der
        self._u_l = float(self._interp_tau(_umbral_izq))
        self._u_r = float(self._interp_tau(_umbral_der))
        _a_l = float(self._interp_tau(_ancla_izq))
        _a_r = float(self._interp_tau(_ancla_der))

        # β despejado para pasar por el ancla (forma cerrada)
        #   p_cond = prob. condicional del ancla dentro de la cola
        #   β = ξ·Δ / ((1-p_cond)^(-ξ) − 1)
        p_cond_r = (_ancla_der - self._tau_r) / max(1.0 - self._tau_r, 1e-12)
        self._beta_r = self._beta_de(abs(_a_r - self._u_r), p_cond_r)
        p_cond_l = (self._tau_l - _ancla_izq) / max(self._tau_l, 1e-12)
        self._beta_l = self._beta_de(abs(self._u_l - _a_l), p_cond_l)

    def _asegurar_grid(self) -> None:
        """Construye la malla de inversión al primer uso de cdf() (ver __init__)."""
        if self._grid_u is not None:
            return
        _u = np.linspace(self._tau_l, self._tau_r, 2001)
        _x = np.asarray(self._ppf_body(_u), dtype=float)
        _ok = ~np.isnan(_x)
        self._grid_u, self._grid_x = _u[_ok], _x[_ok]

    def __getstate__(self):
        """Pickle sin la malla — se reconstruye sola en destino (32KB menos)."""
        return {s: (None if s in ("_grid_u", "_grid_x") else getattr(self, s))
                for s in self.__slots__}

    def __setstate__(self, estado):
        for k, v in estado.items():
            setattr(self, k, v)

    def _interp_tau(self, t: float) -> float:
        """Cuantil en tau t; exacto si t es uno de los nodos observados."""
        idx = np.argmin(np.abs(self._taus - t))
        if abs(self._taus[idx] - t) < 1e-9:
            return float(self._q[idx])
        return float(np.interp(t, self._taus, self._q))

    def _beta_de(self, delta: float, p_cond: float) -> float:
        """β tal que F_GPD(delta) = p_cond. Cerrado; límite exponencial si ξ→0."""
        delta = max(float(delta), 1e-12)
        p_cond = float(np.clip(p_cond, 1e-9, 1.0 - 1e-9))
        xi = self.xi_tail
        if xi < 1e-8:
            return max(delta / max(-np.log(1.0 - p_cond), 1e-12), 1e-12)
        return max(xi * delta / max((1.0 - p_cond) ** (-xi) - 1.0, 1e-12), 1e-12)

    @staticmethod
    def _gpd_cdf(y: np.ndarray, xi: float, beta: float) -> np.ndarray:
        y = np.maximum(y, 0.0)
        if xi < 1e-8:
            return 1.0 - np.exp(-y / beta)
        return 1.0 - np.power(np.maximum(1.0 + xi * y / beta, 1e-300), -1.0 / xi)

    @staticmethod
    def _gpd_ppf(p: np.ndarray, xi: float, beta: float) -> np.ndarray:
        p = np.clip(p, 0.0, 1.0 - 1e-12)
        if xi < 1e-8:
            return -beta * np.log(1.0 - p)
        return (beta / xi) * (np.power(1.0 - p, -xi) - 1.0)

    def cdf(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        out = np.empty_like(x)

        izq = x < self._u_l
        der = x > self._u_r
        cen = ~(izq | der)

        if cen.any():
            # Inversa numérica de ppf() vía la malla densa — garantiza
            # cdf(ppf(u)) = u en todo el cuerpo, no solo en los nodos.
            self._asegurar_grid()
            out[cen] = np.interp(x[cen], self._grid_x, self._grid_u)
        if der.any():
            g = self._gpd_cdf(x[der] - self._u_r, self.xi_tail, self._beta_r)
            out[der] = self._tau_r + (1.0 - self._tau_r) * g
        if izq.any():
            g = self._gpd_cdf(self._u_l - x[izq], self.xi_tail, self._beta_l)
            out[izq] = self._tau_l * (1.0 - g)

        return np.clip(out, 0.0, 1.0)

    def ppf(self, u) -> np.ndarray:
        u = np.atleast_1d(np.asarray(u, dtype=float))
        u = np.clip(u, 1e-12, 1.0 - 1e-12)
        out = np.empty_like(u)

        izq = u < self._tau_l
        der = u > self._tau_r
        cen = ~(izq | der)

        if cen.any():
            vals = self._ppf_body(u[cen])
            out[cen] = np.where(np.isnan(vals),
                                np.interp(u[cen], self._taus, self._q), vals)
        if der.any():
            p_cond = (u[der] - self._tau_r) / max(1.0 - self._tau_r, 1e-12)
            out[der] = self._u_r + self._gpd_ppf(p_cond, self.xi_tail, self._beta_r)
        if izq.any():
            p_cond = 1.0 - u[izq] / max(self._tau_l, 1e-12)
            out[izq] = self._u_l - self._gpd_ppf(p_cond, self.xi_tail, self._beta_l)

        return out

    def __repr__(self) -> str:
        return (f"PchipGPD(xi_tail={self.xi_tail:.4f}, nu_origen={self.nu_origen:.2f}, "
                f"familia={self.familia_origen}, beta_l={self._beta_l:.3e}, "
                f"beta_r={self._beta_r:.3e})")


def _offset_mediana_splitt(scale_l: float, scale_r: float, df: float) -> float:
    """
    Devuelve `d` tal que  mediana(SplitT(loc, scale_l, scale_r, df)) = loc + d.
    Cerrado y exacto — se deriva invirtiendo la PPF de Fernández & Steel en u=0.5:

        p_L = scale_l/(scale_l+scale_r)
        u=0.5 ≤ p_L  →  Q(0.5) = loc + scale_l·t_df.ppf(0.25/p_L)
        u=0.5 >  p_L  →  Q(0.5) = loc − scale_r·t_df.ppf(0.25/p_R)

    Caso simétrico (scale_l=scale_r → p_L=0.5): t_df.ppf(0.5)=0 → d=0, es decir
    mediana = loc, como debe ser. Coste: una llamada a t.ppf, despreciable.
    """
    sl = max(float(scale_l), 1e-12)
    sr = max(float(scale_r), 1e-12)
    p_l = sl / (sl + sr)
    p_r = 1.0 - p_l
    if 0.5 <= p_l:
        return float(sl * stats.t.ppf(0.25 / p_l, df))
    return float(-sr * stats.t.ppf(0.25 / p_r, df))


def _offset_mediana_azzalini(alpha: float, nu: float) -> float:
    """
    Devuelve `m` tal que  mediana(AzzaliniT(xi, omega, alpha, nu)) = xi + omega·m.
    Equivale a la mediana de la skew-t ESTANDARIZADA (xi=0, omega=1), que depende
    solo de (alpha, nu) — no de xi ni omega.

    Sin forma cerrada (la CDF de AC2003 es una integral). Se resuelve en 3 pasos
    aprovechando que _cdf_batch es VECTORIZADO — evaluar 21 puntos cuesta casi
    lo mismo que evaluar 1:
      1. Una sola llamada CDF sobre una malla de 21 puntos en [-2, 2].
      2. Interpolación lineal en el intervalo donde la CDF cruza 0.5.
      3. Dos pasos de Newton usando la PDF (que sí es analítica y barata).

    Frente a un brentq escalar (~12 llamadas CDF de 1 punto), esto usa ~3
    llamadas vectorizadas → el anclaje deja de dominar el coste del fit.
    El rango [-2, 2] es holgado: incluso con |alpha|→∞ la mediana estandarizada
    se queda en torno a ±0.72 (caso half-t).

    Si algo falla, devuelve 0.0 → degrada a "fijar loc" sin romper el fit.
    """
    if abs(alpha) < 1e-9:
        return 0.0            # simétrica: mediana estandarizada = 0 exacto
    try:
        _d   = AzzaliniT(0.0, 1.0, alpha, nu)
        grid = np.linspace(-2.0, 2.0, 21)
        cdfs = _d._cdf_batch(grid)

        # Intervalo donde la CDF cruza 0.5
        idx = int(np.searchsorted(cdfs, 0.5))
        if idx <= 0 or idx >= len(grid):
            # Cruce fuera de la malla (caso patológico): fallback a Brent amplio
            f = lambda z: float(_d._cdf_batch(np.array([z]))[0]) - 0.5
            return float(optimize.brentq(f, -8.0, 8.0, xtol=1e-9, maxiter=100))

        # Interpolación lineal como semilla
        c0, c1 = cdfs[idx - 1], cdfs[idx]
        g0, g1 = grid[idx - 1], grid[idx]
        mm = g0 + (0.5 - c0) * (g1 - g0) / max(c1 - c0, 1e-15)

        # Refinamiento Newton (PDF analítica → convergencia cuadrática)
        for _ in range(2):
            fx = float(_d._cdf_batch(np.array([mm]))[0]) - 0.5
            dx = float(_d._pdf_std(np.array([mm]))[0])
            if abs(dx) < 1e-12:
                break
            mm -= fx / dx
        return float(mm)
    except Exception as _e:
        logger.debug(f"_offset_mediana_azzalini: falló "
                    f"(alpha={alpha:.3f}, nu={nu:.3f}) — {_e}; usando m=0.")
        return 0.0


def fitear_skewt(
    q_vals,
    taus:     list[float],
    n_starts: int = 3,
) -> "AzzaliniT | SplitT":
    """
    Ajusta AzzaliniT y SplitT EN PARALELO bajo la función de pérdida unificada
    PDTC (Probabilistic Distance Tolerance Constraint) y devuelve el ganador.
 
    Función de pérdida (igual para ambas familias — competencia justa):
      L(θ) = Σ_τ w_τ·[F(q_τ;θ) − τ]² + λ·max(0, |F(Q05)−F(Q01)|−ΔT−ε)²
 
    Parámetros PDTC configurables a nivel de módulo:
      PDTC_PESOS   — vector de pesos [w_01, w_05, w_50, w_95, w_99]
      PDTC_LAMBDA  — rigidez λ de la penalización de cola
      PDTC_DELTA_T — distancia teórica entre F(Q05) y F(Q01) = 0.04
      PDTC_EPSILON — holgura ε antes de activar la penalización
 
    Normalización: Z-score con escala = Q95−Q05 (más robusto que Q99−Q01
    ante outliers extremos en los cuantiles de cola).
 
    Si PDTC_PESOS tiene longitud distinta a len(taus), o si Q01/Q05 no están
    presentes en taus, degrada silenciosamente a SSE sin ponderar (sin crash).
    """
    from concurrent.futures import ThreadPoolExecutor
 
    if isinstance(q_vals, dict):
        q_arr = np.array([q_vals[t] for t in taus], dtype=float)
    else:
        q_arr = np.asarray(q_vals, dtype=float)
    taus_arr  = np.array(taus, dtype=float)
    pesos_arr = np.asarray(PDTC_PESOS, dtype=float)
 
    # ── Índices de Q01 y Q05 para la penalización PDTC ───────────────────────
    _idx_q01 = next((i for i, t in enumerate(taus_arr) if abs(t - 0.01) < 1e-6), None)
    _idx_q05 = next((i for i, t in enumerate(taus_arr) if abs(t - 0.05) < 1e-6), None)
    _pdtc_on = (
        _idx_q01 is not None
        and _idx_q05 is not None
        and len(pesos_arr) == len(taus_arr)
    )
 
    # ── Normalización Z-score: mediana / IQR(Q95−Q05) ────────────────────────
    # Paper PDTC usa Q95−Q05 (más robusto que Q99−Q01 ante colas extremas).
    med_idx   = min(range(len(taus)), key=lambda i: abs(taus[i] - 0.50))
    loc0_orig = float(q_arr[med_idx])
    _i_q05    = next((i for i, t in enumerate(taus_arr) if abs(t - 0.05) < 1e-6), None)
    _i_q95    = next((i for i, t in enumerate(taus_arr) if abs(t - 0.95) < 1e-6), None)
    if _i_q05 is not None and _i_q95 is not None:
        escala = max(float(q_arr[_i_q95] - q_arr[_i_q05]), 1e-9)
    else:
        escala = max(float(q_arr.max() - q_arr.min()), 1e-9)   # fallback
    q_norm = (q_arr - loc0_orig) / escala
    spread = max(float(q_norm.max() - q_norm.min()), 1e-6)
    asym   = (q_norm[-1] - q_norm[med_idx]) - (q_norm[med_idx] - q_norm[0])
    alpha0 = float(np.clip(asym / (spread * 0.5 + 1e-9) * 3, -8, 8))
 
    # ── Función de pérdida PDTC unificada ─────────────────────────────────────
    def _pdtc_loss(cdf_calc: np.ndarray) -> float:
        """
        L(θ) = Σ w_τ·[F(q_τ)−τ]² + λ·max(0, |F(Q05)−F(Q01)|−ΔT−ε)²
        Degrada a SSE uniforme si PDTC no aplica (taus incompletos o len distinto).
        """
        if _pdtc_on:
            error_base   = float(np.sum(pesos_arr * (cdf_calc - taus_arr) ** 2))
            dist_cola    = float(cdf_calc[_idx_q05] - cdf_calc[_idx_q01])
            desviacion   = abs(dist_cola - PDTC_DELTA_T)
            penalizacion = (PDTC_LAMBDA * (desviacion - PDTC_EPSILON) ** 2
                            if desviacion > PDTC_EPSILON else 0.0)
        else:
            error_base   = float(np.sum((cdf_calc - taus_arr) ** 2))
            penalizacion = 0.0
        return error_base + penalizacion
 
    # ── Fit AzzaliniT con PDTC (thread A) ────────────────────────────────────
    # _cdf_batch toma z = (x−xi)/omega (variable estandarizada, NO xi/omega).
    # Se pasa (q_norm − xi_n) / om_n para que el optimizador mueva xi y omega.
    def _fit_az() -> tuple:
        _anclar = FIJAR_MED_EN_Q50

        def _xi_de(om_n: float, al_n: float, nu_n: float) -> float:
            """
            xi que ancla la MEDIANA en Q50. En espacio normalizado Q50 → 0, y
            mediana = xi + omega·m(alpha,nu), así que exigir mediana=0 da
            xi = −omega·m. No es "xi = Q50" a secas: es el xi que hace que la
            mediana ajustada caiga exactamente en Q50 (coinciden solo si alpha=0).
            """
            return -om_n * _offset_mediana_azzalini(al_n, nu_n)

        starts_full = [
            [0.0, spread * 0.40,  0.0,    6.0],
            [0.0, spread * 0.35,  alpha0, 4.0],
            [0.0, spread * 0.35, -alpha0, 4.0],
        ][:n_starts]
        bounds_full = [
            (q_norm.min() - spread, q_norm.max() + spread),  # xi
            (1e-6, 8.0 * spread),                             # omega
            (-15.0, 15.0),                                    # alpha
            (2.01,  120.0),                                   # nu
        ]
        # Con anclaje, xi (índice 0) sale del vector de parámetros: el
        # optimizador queda con 3 grados de libertad (omega, alpha, nu).
        starts_az = [s[1:] for s in starts_full] if _anclar else starts_full
        bounds_az = bounds_full[1:]              if _anclar else bounds_full

        def _desempaquetar_az(p):
            if _anclar:
                om_n, al_n, nu_n = p
                return _xi_de(om_n, al_n, nu_n), om_n, al_n, nu_n
            return tuple(p)

        def obj_az(p):
            xi_n, om_n, al_n, nu_n = _desempaquetar_az(p)
            if om_n <= 0 or nu_n <= 2.0:
                return 1e6
            try:
                d        = AzzaliniT(xi_n, om_n, al_n, nu_n)
                cdf_calc = d._cdf_batch((q_norm - xi_n) / om_n)
                return _pdtc_loss(cdf_calc)
            except Exception:
                return 1e6

        mejor = None
        for x0 in starts_az:
            try:
                res = optimize.minimize(obj_az, x0, method="L-BFGS-B", bounds=bounds_az,
                                        options={"maxiter": 800, "ftol": 1e-15, "gtol": 1e-11})
                if mejor is None or res.fun < mejor.fun:
                    mejor = res
            except Exception as _e:
                logger.debug(f"_fit_az: L-BFGS-B falló x0={x0} — {_e}")

        if mejor is None:
            return None, float("inf")
        try:
            xi_n, om_n, al_n, nu_n = _desempaquetar_az(mejor.x)
            d    = AzzaliniT(xi_n * escala + loc0_orig, om_n * escala, al_n, nu_n)
            loss = _pdtc_loss(d.cdf(q_arr))   # evaluado en espacio original
            return d, loss
        except Exception as _e:
            logger.debug(f"_fit_az: construcción AzzaliniT falló — {_e}")
            return None, float("inf")
 
    # ── Fit SplitT con PDTC (thread B) ───────────────────────────────────────
    # SplitT.fit_from_quantiles usa SSE uniforme — reemplazado aquí por PDTC.
    # SplitT.cdf(q_norm) aplica (x−loc)/scale_l/r internamente → correcto.
    def _fit_st() -> tuple:
        _anclar = FIJAR_MED_EN_Q50

        def _loc_de(sl_n: float, sr_n: float, df_n: float) -> float:
            """
            loc que ancla la MEDIANA en Q50. En espacio normalizado Q50 → 0, y
            mediana = loc + d(sl,sr,df), así que exigir mediana=0 da loc = −d.
            A diferencia de AzzaliniT, aquí d es cerrado (una t.ppf) → coste
            despreciable, sin búsqueda numérica.
            """
            return -_offset_mediana_splitt(sl_n, sr_n, df_n)

        starts_full = [
            [0.0, spread * 0.25, spread * 0.25,  6.0],
            ([0.0, spread * 0.15, spread * 0.35, 4.0] if alpha0 < 0
             else [0.0, spread * 0.35, spread * 0.15, 4.0]),
            [0.0, spread * 0.20, spread * 0.20, 10.0],
        ][:n_starts]
        bounds_full = [
            (q_norm.min() - spread, q_norm.max() + spread),  # loc
            (1e-6, 8.0 * spread),                             # scale_l
            (1e-6, 8.0 * spread),                             # scale_r
            (2.01, 120.0),                                    # df
        ]
        # Con anclaje, loc (índice 0) sale del vector: quedan 3 grados de
        # libertad (scale_l, scale_r, df) — todos de forma/colas.
        starts_st = [s[1:] for s in starts_full] if _anclar else starts_full
        bounds_st = bounds_full[1:]              if _anclar else bounds_full

        def _desempaquetar_st(p):
            if _anclar:
                sl_n, sr_n, df_n = p
                return _loc_de(sl_n, sr_n, df_n), sl_n, sr_n, df_n
            return tuple(p)

        def obj_st(p):
            loc_n, sl_n, sr_n, df_n = _desempaquetar_st(p)
            if sl_n <= 0 or sr_n <= 0 or df_n <= 2.0:
                return 1e6
            try:
                d        = SplitT(loc_n, sl_n, sr_n, df_n)
                cdf_calc = d.cdf(q_norm)
                return _pdtc_loss(cdf_calc)
            except Exception:
                return 1e6

        mejor = None
        for x0 in starts_st:
            try:
                res = optimize.minimize(obj_st, x0, method="L-BFGS-B", bounds=bounds_st,
                                        options={"maxiter": 800, "ftol": 1e-15, "gtol": 1e-11})
                if mejor is None or res.fun < mejor.fun:
                    mejor = res
            except Exception as _e:
                logger.debug(f"_fit_st: L-BFGS-B falló x0={x0} — {_e}")

        if mejor is None:
            return None, float("inf")
        try:
            loc_n, sl_n, sr_n, df_n = _desempaquetar_st(mejor.x)
            d    = SplitT(loc_n * escala + loc0_orig,
                          sl_n  * escala, sr_n * escala, df_n)
            loss = _pdtc_loss(d.cdf(q_arr))   # evaluado en espacio original
            return d, loss
        except Exception as _e:
            logger.debug(f"_fit_st: construcción SplitT falló — {_e}")
            return None, float("inf")
 
    # ── Ejecución en paralelo ─────────────────────────────────────────────────
    with ThreadPoolExecutor(max_workers=2) as ex:
        fut_az = ex.submit(_fit_az)
        fut_st = ex.submit(_fit_st)
        dist_az, loss_az = fut_az.result()
        dist_st, loss_st = fut_st.result()
 
    # ── Selección del ganador (mismo criterio PDTC para ambos) ───────────────
    def _log_ganador(dist, loss_win, loss_lose, nombre_lose):
        if isinstance(dist, AzzaliniT):
            params = (f"xi={dist.xi:.3e}  omega={dist.omega:.3e}  "
                      f"alpha={dist.alpha:+.3f}  nu={dist.nu:.1f}")
            if dist.nu < 2.5:
                logger.warning(f"fitear_skewt [AzzaliniT]: nu={dist.nu:.2f} en límite "
                               f"inferior — colas muy pesadas, Q01/Q99 puede ser impreciso.")
        else:
            params = (f"loc={dist.loc:.3e}  scale_l={dist.scale_l:.3e}  "
                      f"scale_r={dist.scale_r:.3e}  df={dist.df:.1f}")
            if dist.df < 2.5:
                logger.warning(f"fitear_skewt [SplitT]: df={dist.df:.2f} en límite "
                               f"inferior — colas muy pesadas, Q01/Q99 puede ser impreciso.")
        logger.debug(f"fitear_skewt: {type(dist).__name__} gana  "
                     f"PDTC_loss={loss_win:.2e} vs {nombre_lose}={loss_lose:.2e}  {params}")
 
    def _envolver_hibrido(dist_param):
        """
        Envuelve el ganador paramétrico en PchipGPD si el toggle está activo.
        El fit paramétrico NO se descarta: su ν pasa a ser el índice de cola
        (ξ=1/ν) de la GPD, mientras el cuerpo lo toma PCHIP directo de los
        cuantiles. Si algo falla, devuelve el paramétrico sin envolver — el
        híbrido nunca puede degradar el comportamiento actual.
        """
        if not FITEO_HIBRIDO_PCHIP_GPD:
            return dist_param
        try:
            _nu = dist_param.nu if isinstance(dist_param, AzzaliniT) else dist_param.df
            return PchipGPD(q_arr, taus_arr, nu=_nu,
                            familia_origen=type(dist_param).__name__)
        except Exception as _e:
            logger.warning(f"fitear_skewt: PchipGPD falló ({type(_e).__name__}: {_e}) "
                          f"— usando el ajuste paramétrico sin envolver.")
            return dist_param

    if dist_az is not None and loss_az <= loss_st:
        dist_az._build_ppf_grid()
        _log_ganador(dist_az, loss_az, loss_st, "SplitT")
        return _envolver_hibrido(dist_az)

    if dist_st is not None:
        _log_ganador(dist_st, loss_st, loss_az, "AzzaliniT")
        return _envolver_hibrido(dist_st)

    # ── Último recurso si ambos fallan ────────────────────────────────────────
    logger.warning("fitear_skewt: fallo total — usando SplitT IQR como último recurso")
    iqr = max((q_arr[-1] - q_arr[0]) / 4.0, 1.0)
    return SplitT(float(loc0_orig), iqr, iqr, 6.0)


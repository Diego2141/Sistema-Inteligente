# PARTE 5 — Simulación masiva de paths y acumulado por ventana
# ══════════════════════════════════════════════════════════════════════════════

def _resolver_estado_inicial(estado_inicial, fecha_t, default: int = 0) -> int:
    """
    Permite que estado_inicial sea:
      - un int  : mismo estado para todos los orígenes (comportamiento original,
                  útil para proyectar hacia adelante desde "hoy").
      - un dict o pd.Series {fecha_t: estado} : estado propio de CADA origen,
                  el caso correcto para backtest histórico — usa el régimen
                  que el HMM clasificó ese día específico (columna 'regimen_hmm'
                  ya guardada por step005_walk_forward_cv*.py), en vez de asumir
                  que todo el período de test parte del mismo régimen.
    Si fecha_t no está en el mapeo, devuelve `default` (con aviso una sola vez
    por ejecución, vía logger, no por cada origen — evita espamear el log).
    """
    if isinstance(estado_inicial, (dict, pd.Series)):
        try:
            val = estado_inicial[fecha_t]
        except KeyError:
            return default
        if pd.isna(val):
            return default
        return int(val)
    return int(estado_inicial)


def simular_paths_por_origen(
    fecha_t:          pd.Timestamp,
    df_origen:        pd.DataFrame,
    distribuciones:   dict[tuple, SplitT],
    estado_inicial:   int,
    matriz_transicion: np.ndarray,
    rho_por_regimen:  dict[int, float],
    n_paths:          int,
    ventanas:         list[int],
    prophet_col:      str | None = "prophet_pred",
    seed:             int = 42,
) -> dict[int, np.ndarray]:
    """
    Para una fecha de origen dada, simula n_paths paths y devuelve la
    distribución del flujo acumulado para cada ventana.

    Parámetros
    ----------
    fecha_t           : fecha de origen del forecast.
    df_origen         : filas de df_preds con fecha_t == fecha_t,
                        ordenadas por h ascendente.
    distribuciones    : dict {(fecha_t, h): SplitT}.
    estado_inicial    : estado HMM actual (int).
    matriz_transicion : array (n_estados × n_estados).
    rho_por_regimen   : {estado: ρ_s}.
    n_paths           : número de paths a simular.
    ventanas          : lista de plazos en días hábiles, e.g. [1,5,22,75].
    prophet_col       : nombre de la columna con el forecast determinista de
                        Prophet (None si no se usa).
    seed              : semilla base para reproducibilidad.

    Devuelve
    --------
    dict {ventana: array de shape (n_paths,)} — distribuciones del acumulado.
    """
    df_origen = df_origen.sort_values("h").reset_index(drop=True)
    horizontes = df_origen["h"].values.astype(int)
    H          = len(horizontes)

    prophet_vals = (
        df_origen[prophet_col].values
        if (prophet_col is not None and prophet_col in df_origen.columns)
        else np.zeros(H)
    )

    rng_base  = np.random.default_rng(seed)
    # Simular secuencias de régimen (una por path)
    # Reutilizamos la misma semilla base pero streams independientes por path
    acum_por_ventana: dict[int, list[float]] = {v: [] for v in ventanas}

    for p in range(n_paths):
        rng_p = np.random.default_rng(seed + p)

        # Sorteo 1: secuencia de régimen
        regimenes = simular_regimen_path(
            estado_inicial, matriz_transicion, H, rng_p)

        # Sorteo 2: residuos correlacionados vía AR(1) copula
        residuos = simular_un_path(
            fecha_t, horizontes, regimenes,
            rho_por_regimen, distribuciones, rng_p)

        # Flujo simulado = Prophet + residuo
        flujos = prophet_vals + residuos

        # Acumular por cada ventana
        for v in ventanas:
            idx = np.where(horizontes <= v)[0]
            if len(idx) > 0:
                acum_por_ventana[v].append(float(flujos[idx].sum()))
            else:
                acum_por_ventana[v].append(0.0)

    return {v: np.array(lst) for v, lst in acum_por_ventana.items()}


def calcular_percentiles_acumulado(
    distribuciones_acum: dict[int, np.ndarray],
    taus_output:         list[float] | None = None,
) -> dict[int, dict[float, float]]:
    """
    Extrae percentiles de la distribución del acumulado por ventana.

    Devuelve
    --------
    dict {ventana: {tau: valor_percentil}}
    """
    if taus_output is None:
        taus_output = [0.01, 0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95, 0.99]

    resultado = {}
    for v, arr in distribuciones_acum.items():
        resultado[v] = {t: float(np.quantile(arr, t)) for t in taus_output}
    return resultado



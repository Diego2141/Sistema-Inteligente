# PARTE 9 — Fan charts de flujo acumulado por día de origen
# ══════════════════════════════════════════════════════════════════════════════
#
# A diferencia del backtest (que solo necesita el acumulado en 4 ventanas
# discretas: [1,5,22,75]), el fan chart necesita el acumulado en CADA
# horizonte h, para dibujar una banda que se ensancha de forma continua.
# simular_fanchart_origen calcula esto de forma eficiente: una sola pasada de
# cumsum por path (O(H)), en vez de recomputar la suma para cada ventana por
# separado (O(H²) si se reusara simular_paths_por_origen con un ventanas denso).

def simular_fanchart_origen(
    fecha_t:           pd.Timestamp,
    horizontes:        np.ndarray,
    estado_inicial:    int,
    matriz_transicion: np.ndarray,
    rho_por_regimen:   dict[int, float],
    distribuciones:    dict[tuple, SplitT],
    n_paths:           int,
    prophet_vals:      np.ndarray | None = None,
    seed:              int = 42,
) -> np.ndarray:
    """
    Simula n_paths paths para UN origen y devuelve el flujo ACUMULADO en
    CADA horizonte (no solo en ventanas discretas), vía cumsum — O(H) por
    path.

    Devuelve
    --------
    array de shape (n_paths, len(horizontes)); columna k = distribución del
    acumulado desde el origen hasta horizontes[k] (ambos extremos incluidos,
    sin contar el punto de anclaje h=0=0 que se agrega al graficar).
    """
    H = len(horizontes)
    acumulados = np.empty((n_paths, H))
    for p in range(n_paths):
        rng_p = np.random.default_rng(seed + p)
        regimenes = simular_regimen_path(estado_inicial, matriz_transicion, H, rng_p)
        residuos  = simular_un_path(fecha_t, horizontes, regimenes,
                                    rho_por_regimen, distribuciones, rng_p)
        flujos = (prophet_vals if prophet_vals is not None else 0.0) + residuos
        acumulados[p, :] = np.cumsum(flujos)
    return acumulados


# Bandas de percentiles para el fan chart, de la más angosta (centro, más
# OSCURA) a la más ancha (extremos, más CLARA) — convención estándar de fan
# chart (estilo Bank of England).
BANDAS_FANCHART_DEFAULT = [
    (0.40, 0.60), (0.30, 0.70), (0.20, 0.80),
    (0.10, 0.90), (0.05, 0.95), (0.01, 0.99),
]


def graficar_fanchart_origen(
    fecha_t:                pd.Timestamp,
    horizontes:             np.ndarray,
    acumulados:             np.ndarray,
    y_realizado_acum_por_h: dict[int, float],
    dir_salida:             Path,
    banco:                  str = "SISTEMA",
    bandas:                 list[tuple[float, float]] | None = None,
    color_base:             str = "#1565C0",
) -> Path:
    """
    Dibuja y guarda un fan chart de flujo acumulado para UN origen.

    Las bandas se dibujan de la más ANCHA a la más ANGOSTA (en ese orden),
    cada una con más opacidad que la anterior. Como están anidadas (la
    angosta es un subconjunto visual de la ancha) y matplotlib compone los
    alphas por capas, el centro queda más oscuro (cubierto por todas las
    capas) y los extremos más claros (cubiertos solo por la capa más ancha)
    — el degradado pedido, sin necesitar un gradiente continuo explícito.

    Tanto las bandas proyectadas como la línea realizada arrancan en
    (h=0, valor=0): el origen mismo, donde no hay incertidumbre ni
    acumulado todavía.
    """
    if bandas is None:
        bandas = BANDAS_FANCHART_DEFAULT

    x = [0] + horizontes.tolist()
    # figsize×dpi=120 da 1200×672 px, ambos múltiplos de 16 — evita que
    # ffmpeg tenga que redimensionar al ensamblar el video (generar_video_
    # fancharts.py), que de otro modo emite un aviso (inofensivo, pero evitable).
    fig, ax = plt.subplots(figsize=(10, 5.6))

    # de más ancha a más angosta (alpha creciente => más oscura encima)
    bandas_ordenadas = sorted(bandas, key=lambda b: (b[1] - b[0]), reverse=True)
    n_bandas = len(bandas_ordenadas)
    for i, (lo_t, hi_t) in enumerate(bandas_ordenadas):
        alpha = 0.10 + 0.55 * (i + 1) / n_bandas
        lo_vals = [0.0] + [float(np.quantile(acumulados[:, k], lo_t))
                           for k in range(len(horizontes))]
        hi_vals = [0.0] + [float(np.quantile(acumulados[:, k], hi_t))
                           for k in range(len(horizontes))]
        ax.fill_between(x, lo_vals, hi_vals, color=color_base,
                        alpha=alpha, linewidth=0, zorder=2)

    med_vals = [0.0] + [float(np.quantile(acumulados[:, k], 0.50))
                        for k in range(len(horizontes))]
    ax.plot(x, med_vals, color=color_base, lw=1.4, ls="--",
           label="Mediana proyectada", zorder=3)

    y_real = [0.0] + [y_realizado_acum_por_h.get(int(h), np.nan) for h in horizontes]
    ax.plot(x, y_real, color="black", lw=1.9, label="Realizado acumulado", zorder=4)

    ax.axhline(0, color="grey", lw=0.6, ls=":", zorder=1)
    ax.set_xlabel("Horizonte (días hábiles desde el origen)")
    ax.set_ylabel("Flujo neto acumulado")
    ax.set_title(f"{banco} — Fan chart de flujo acumulado\nOrigen: {fecha_t.date()}",
                fontsize=11, fontweight="bold")
    ax.legend(loc="upper left", fontsize=8, framealpha=0.9)
    ax.set_xlim(0, max(x))
    plt.tight_layout()

    dir_salida = Path(dir_salida)
    dir_salida.mkdir(parents=True, exist_ok=True)
    nombre = f"fanchart_{banco}_{fecha_t.strftime('%Y%m%d')}.png"
    ruta = dir_salida / nombre
    # SIN bbox_inches="tight": ese recorte depende del contenido (ancho de
    # etiquetas del eje Y varía con la magnitud de cada origen) y podría dar
    # tamaños de imagen distintos entre fechas — rompería el ensamblado de
    # video más adelante (generar_video_fancharts.py necesita frames
    # uniformes). tight_layout() ya ajusta el layout antes de guardar; el
    # tamaño final queda fijo en figsize×dpi = 1200×672 px siempre.
    fig.savefig(ruta, dpi=120)
    plt.close(fig)
    return ruta


def generar_fancharts_todos_origenes(
    df_preds:          pd.DataFrame,
    distribuciones:    dict[tuple, SplitT],
    estado_inicial:    int | dict | pd.Series,
    matriz_transicion: np.ndarray,
    rho_por_regimen:   dict[int, float],
    dir_salida:        Path,
    banco:             str = "SISTEMA",
    n_paths:           int = 1000,
    prophet_col:       str | None = None,
    h_col:             str = "h",
    fecha_col:         str = "fecha_t",
    seed:              int = 42,
    bandas:            list[tuple[float, float]] | None = None,
) -> list[Path]:
    """
    Genera un fan chart PNG por cada fecha de origen en df_preds, guardado en
    dir_salida. Reusa `distribuciones` ya fiteadas (no vuelve a ajustar
    SplitT — ese es el costo dominante, ya pagado por quien llame a esta
    función junto con pipeline_simulacion).

    Devuelve la lista de rutas de los PNGs generados, en orden cronológico.
    """
    df_preds = df_preds.copy()
    df_preds[fecha_col] = pd.to_datetime(df_preds[fecha_col])

    fechas_origen = sorted(df_preds[fecha_col].unique())
    n_or = len(fechas_origen)
    logger.info(f"  [fanchart] Generando {n_or} fan charts en {dir_salida}...")

    rutas = []
    for idx_o, fecha_t in enumerate(fechas_origen):
        fecha_t = pd.Timestamp(fecha_t)
        df_orig = df_preds[df_preds[fecha_col] == fecha_t].sort_values(h_col)
        horizontes = df_orig[h_col].values.astype(int)
        y_real     = df_orig["y_realizado"].values.astype(float)
        prophet_vals = (df_orig[prophet_col].values
                       if (prophet_col is not None and prophet_col in df_orig.columns)
                       else None)

        estado_o = _resolver_estado_inicial(estado_inicial, fecha_t)
        acumulados = simular_fanchart_origen(
            fecha_t, horizontes, estado_o, matriz_transicion, rho_por_regimen,
            distribuciones, n_paths, prophet_vals=prophet_vals, seed=seed + idx_o,
        )

        y_realizado_acum_por_h = dict(zip(horizontes.tolist(),
                                          np.cumsum(y_real).tolist()))

        ruta = graficar_fanchart_origen(
            fecha_t, horizontes, acumulados, y_realizado_acum_por_h,
            dir_salida, banco=banco, bandas=bandas,
        )
        rutas.append(ruta)

        if (idx_o + 1) % 25 == 0:
            logger.info(f"    [fanchart] {idx_o+1}/{n_or}")

    logger.info(f"  [fanchart] {len(rutas)} imágenes generadas")
    return rutas



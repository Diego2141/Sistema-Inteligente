# PARTE 6 — Pipeline completo: múltiples orígenes
# ══════════════════════════════════════════════════════════════════════════════

def pipeline_simulacion(
    df_preds:          pd.DataFrame,
    estado_inicial:    int | dict | pd.Series,
    matriz_transicion: np.ndarray,
    rho_por_regimen:   dict[int, float],
    ventanas:          list[int]  | None = None,
    taus_input:        list[float] | None = None,
    taus_output:       list[float] | None = None,
    n_paths:           int  = 1000,
    prophet_col:       str | None = "prophet_pred",
    h_col:             str  = "h",
    fecha_col:         str  = "fecha_t",
    seed:              int  = 42,
    n_jobs:            int  = -1,
    distribuciones:    dict[tuple, SplitT] | None = None,
) -> pd.DataFrame:
    """
    Pipeline completo para todas las fechas de origen en df_preds.

    Parámetros
    ----------
    df_preds          : DataFrame con predicciones de step005, columnas:
                         fecha_t | h | y_realizado | q01 | q05 | q50 | q95 | q99
                         (+ prophet_pred opcional).
    estado_inicial    : estado HMM a usar como punto de partida de cada origen.
                         - int: mismo estado para TODOS los orígenes (proyección
                           hacia adelante desde "hoy", como en el test sintético).
                         - dict o pd.Series {fecha_t: estado}: el estado propio
                           de CADA origen (correcto para backtest histórico —
                           usa la columna 'regimen_hmm' real de cada fila).
    matriz_transicion : array (n_estados × n_estados) del HMM.
    rho_por_regimen   : {estado: ρ_s}, un ρ por régimen.
    ventanas          : plazos en días hábiles, default [1, 5, 22, 75].
    taus_input        : cuantiles del df_preds, default [0.01,0.05,0.50,0.95,0.99].
    taus_output       : cuantiles del acumulado a reportar.
    n_paths           : paths por fecha de origen.
    prophet_col       : columna con forecast de Prophet (None si no aplica).
    seed              : semilla base.
    n_jobs            : procesos paralelos para fitear las distribuciones
                         (ver fitear_distribuciones_por_horizonte). -1 = todos
                         los cores; 1 = serial.
    distribuciones    : dict {(fecha_t,h): SplitT} ya fiteado, si se quiere
                         REUSAR el ajuste (p.ej. compartido con
                         generar_fancharts_todos_origenes para no fitear las
                         mismas skew-t dos veces — ese es el costo dominante
                         del pipeline). Si None, se fitea aquí como siempre.

    Devuelve
    --------
    DataFrame con columnas:
      fecha_t | ventana | tau | percentil_acum | y_realizado_acum
    """
    if ventanas is None:
        ventanas = [1, 5, 22, 75]
    if taus_input is None:
        taus_input = TAUS_STD
    if taus_output is None:
        taus_output = [0.01, 0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95, 0.99]

    df_preds = df_preds.copy()
    df_preds[fecha_col] = pd.to_datetime(df_preds[fecha_col])

    # ── Fit global: una SplitT por cada (fecha_t, h) — o reusar si ya viene ──
    if distribuciones is None:
        logger.info("  [step006] Fiteando distribuciones split-t por horizonte...")
        distribuciones = fitear_distribuciones_por_horizonte(
            df_preds, taus_input, n_jobs=n_jobs)
    else:
        logger.info("  [step006] Reusando distribuciones split-t ya fiteadas...")

    # ── Calcula acumulado realizado por ventana, por fecha_t ─────────────────
    real_acum: dict[str, dict[int, float]] = {}
    for fecha_t, grp in df_preds.groupby(fecha_col):
        grp_s = grp.sort_values(h_col)
        hs    = grp_s[h_col].values
        ys    = grp_s["y_realizado"].values
        real_acum[str(fecha_t)] = {}
        for v in ventanas:
            idx = np.where(hs <= v)[0]
            real_acum[str(fecha_t)][v] = float(ys[idx].sum()) if len(idx) else np.nan

    # ── Simula paths por origen ───────────────────────────────────────────────
    fechas_origen = sorted(df_preds[fecha_col].unique())
    n_or = len(fechas_origen)
    logger.info(f"  [step006] Simulando {n_paths} paths × {n_or} orígenes × "
                f"{len(ventanas)} ventanas...")

    resultados = []
    for idx_o, fecha_t in enumerate(fechas_origen):
        df_orig = df_preds[df_preds[fecha_col] == fecha_t]
        estado_o = _resolver_estado_inicial(estado_inicial, fecha_t)
        dist_acum = simular_paths_por_origen(
            fecha_t, df_orig, distribuciones,
            estado_o, matriz_transicion, rho_por_regimen,
            n_paths=n_paths, ventanas=ventanas,
            prophet_col=prophet_col, seed=seed + idx_o,
        )
        pctiles = calcular_percentiles_acumulado(dist_acum, taus_output)

        for v, tmap in pctiles.items():
            y_real = real_acum.get(str(fecha_t), {}).get(v, np.nan)
            for tau, val in tmap.items():
                resultados.append({
                    "fecha_t":           fecha_t,
                    "ventana":           v,
                    "tau":               tau,
                    "percentil_acum":    val,
                    "y_realizado_acum":  y_real,
                })

        if (idx_o + 1) % 50 == 0:
            logger.info(f"    [step006] Origen {idx_o+1}/{n_or}")

    df_out = pd.DataFrame(resultados)
    logger.info(f"  [step006] Pipeline completo: {len(df_out):,} filas")
    return df_out



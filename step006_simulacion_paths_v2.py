# PARTE 7b — Fan chart de flujo NETO diario y backtest puntual
# ══════════════════════════════════════════════════════════════════════════════
#
# Complemento del fan chart acumulado:
#   · Fan chart neto: muestra la distribución AzzaliniT de CADA horizonte h
#     como bandas de percentiles (no acumuladas). No necesita simulación —
#     los percentiles se leen directamente de las distribuciones ya fiteadas.
#     Las bandas no son necesariamente monótonas en h (la incertidumbre
#     pointwise no crece con el horizonte de la misma forma que la acumulada).
#   · Backtest neto: 3 piezas para τ ∈ TAUS_BACKTEST (por defecto [0.01, 0.05])
#     aplicadas directamente a las filas (fecha_t, h, y_realizado vs q_tau),
#     sin simulación. Mide calibración pointwise del XGBoost+AzzaliniT,
#     distinto del backtest acumulado que mide la cobertura del colchón.


def graficar_fanchart_neto_origen(
    fecha_t:           pd.Timestamp,
    horizontes:        np.ndarray,
    distribuciones:    dict[tuple, "AzzaliniT"],
    y_realizado_por_h: dict[int, float],
    dir_salida:        Path,
    banco:             str = "SISTEMA",
    bandas:            list[tuple[float, float]] | None = None,
    color_base:        str = "#1565C0",
) -> Path:
    """
    Fan chart de flujo neto DIARIO para UN origen, extrayendo los percentiles
    directamente de las distribuciones AzzaliniT ajustadas (sin simulación).

    A diferencia del fan chart acumulado:
      · No parte de (h=0, valor=0): cada horizonte tiene su propia distribución
        independiente centrada en su mediana predicha.
      · Las bandas pueden no ser monótonas — es información real sobre cómo
        varía la incertidumbre pointwise con el horizonte.
      · La línea realizada muestra y_realizado para cada h directamente.
    """
    if bandas is None:
        bandas = BANDAS_FANCHART_DEFAULT

    x = horizontes.tolist()
    fig, ax = plt.subplots(figsize=(10, 5.6))

    # Extraer percentiles de cada distribución analíticamente
    bandas_ord = sorted(bandas, key=lambda b: (b[1] - b[0]), reverse=True)
    n_bandas   = len(bandas_ord)

    for i, (lo_t, hi_t) in enumerate(bandas_ord):
        alpha = 0.10 + 0.55 * (i + 1) / n_bandas
        lo_vals, hi_vals = [], []
        for h in horizontes:
            dist = distribuciones.get((pd.Timestamp(fecha_t), int(h)))
            if dist is not None:
                lo_vals.append(float(dist.ppf(np.array([lo_t]))[0]))
                hi_vals.append(float(dist.ppf(np.array([hi_t]))[0]))
            else:
                lo_vals.append(np.nan)
                hi_vals.append(np.nan)
        ax.fill_between(x, lo_vals, hi_vals, color=color_base,
                        alpha=alpha, linewidth=0, zorder=2)

    med_vals = []
    for h in horizontes:
        dist = distribuciones.get((pd.Timestamp(fecha_t), int(h)))
        med_vals.append(float(dist.ppf(np.array([0.50]))[0]) if dist else np.nan)
    ax.plot(x, med_vals, color=color_base, lw=1.4, ls="--",
            label="Mediana proyectada", zorder=3)

    y_real = [y_realizado_por_h.get(int(h), np.nan) for h in horizontes]
    ax.plot(x, y_real, color="black", lw=1.9, label="Realizado", zorder=4)

    ax.axhline(0, color="grey", lw=0.6, ls=":", zorder=1)
    ax.set_xlabel("Horizonte (días hábiles desde el origen)")
    ax.set_ylabel("Flujo neto diario")
    ax.set_title(f"{banco} — Fan chart de flujo neto\nOrigen: {fecha_t.date()}",
                 fontsize=11, fontweight="bold")
    ax.legend(loc="upper left", fontsize=8, framealpha=0.9)
    ax.set_xlim(min(x), max(x))
    plt.tight_layout()

    dir_salida = Path(dir_salida)
    dir_salida.mkdir(parents=True, exist_ok=True)
    ruta = dir_salida / f"fanchart_neto_{banco}_{fecha_t.strftime('%Y%m%d')}.png"
    fig.savefig(ruta, dpi=120)
    plt.close(fig)
    return ruta



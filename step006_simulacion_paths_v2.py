# ══════════════════════════════════════════════════════════════════════════════
# PARTE 1 — Azzalini-Capitanio skew-t (AC2003)
# ══════════════════════════════════════════════════════════════════════════════
#
# Referencia: Azzalini, A. & Capitanio, A. (2003). "Distributions generated by
# perturbation of symmetry with emphasis on a multivariate skew-t distribution."
# Journal of the Royal Statistical Society B, 65(2), 367-389.
#
# Parámetros: xi (localización), omega (escala > 0), alpha (forma ∈ ℝ), nu (df > 2)
#
# PDF:  f(x; xi, omega, alpha, nu) =
#         (2/omega) · t_nu((x-xi)/omega) · T_{nu+1}(alpha · z · sqrt((nu+1)/(nu+z²)))
#
# donde z = (x-xi)/omega, t_nu = PDF de t-Student con nu df,
#       T_{nu+1} = CDF de t-Student con nu+1 df  ← clave AC2003 (no nu).
#
# CDF: No tiene forma cerrada. Se calcula vía cuadratura Gauss-Legendre con
#      cambio de variable u = t/(1+|t|) que compacta ℝ en (-1,1), permitiendo
#      nodos fijos y pesos fijos precomputados para integración vectorizada.
#
# PPF: Sin forma cerrada. Se precalcula una malla de 200 cuantiles con Newton
#      (usando el PDF analítico como derivada), y luego se interpola linealmente.
#      La malla se construye una sola vez por objeto (lazy o eagerly en fitear_skewt).

# Nodos y pesos GL de grado 80 precomputados a nivel de módulo (thread-safe,
# inmutables). Orden 80 garantiza ~15 dígitos de precisión para funciones suaves.
_GL_NODES, _GL_WEIGHTS = np.polynomial.legendre.leggauss(80)


class AzzaliniT:
    """
    Distribución skew-t de Azzalini & Capitanio (2003).

    Parámetros
    ----------
    xi    : localización
    omega : escala (> 0)
    alpha : forma/asimetría (ℝ; alpha=0 → t-Student simétrica)
    nu    : grados de libertad (> 2 para varianza finita)
    """

    _PPF_N     = 200          # puntos en la malla de PPF
    _PPF_U_MIN = 1e-4         # límite inferior de la malla (evita divergencia)
    _PPF_U_MAX = 1.0 - 1e-4  # límite superior
    _PPF_ITER  = 20           # máximo de iteraciones Newton
    _PPF_TOL   = 1e-9         # tolerancia de convergencia Newton

    __slots__ = ("xi", "omega", "alpha", "nu", "_ppf_u", "_ppf_x")

    def __init__(self, xi: float, omega: float, alpha: float, nu: float):
        self.xi    = float(xi)
        self.omega = max(float(omega), 1e-12)
        self.alpha = float(alpha)
        self.nu    = max(float(nu), 2.01)
        self._ppf_u: np.ndarray | None = None
        self._ppf_x: np.ndarray | None = None

    # ── PDF analítico ─────────────────────────────────────────────────────────

    def _pdf_std(self, z: np.ndarray) -> np.ndarray:
        """
        PDF estandarizada (xi=0, omega=1) en un array de puntos z.
        Implementa exactamente la ecuación (4) de AC2003:
          2 · t_nu(z) · T_{nu+1}(alpha · z · sqrt((nu+1)/(nu+z²)))
        Nota: T_{nu+1} usa nu+1 grados de libertad — detalle crítico de AC2003.
        """
        t_pdf = stats.t.pdf(z, df=self.nu)
        with np.errstate(invalid="ignore", divide="ignore"):
            denom = np.maximum(self.nu + z ** 2, 1e-300)
            inner = self.alpha * z * np.sqrt((self.nu + 1.0) / denom)
        t_cdf = stats.t.cdf(inner, df=self.nu + 1.0)   # nu+1, no nu
        return 2.0 * t_pdf * t_cdf

    def pdf(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return self._pdf_std((x - self.xi) / self.omega) / self.omega

    # ── CDF vía Gauss-Legendre vectorizado ────────────────────────────────────

    def _cdf_batch(self, z_arr: np.ndarray) -> np.ndarray:
        """
        CDF estandarizada en un array de puntos z_arr, calculada simultáneamente.

        Cambio de variable: u = t/(1+|t|) compacta ℝ → (-1,1).
          Inversa: t = u/(1-|u|)
          Jacobiano: dt/du = 1/(1-|u|)²
        Integración GL en [-1, u_upper] donde u_upper = z/(1+|z|).

        Vectoriza sobre z_arr: construye tensor (n_z × n_GL) en un solo bloque
        numpy, evitando el loop Python sobre puntos z. Esencial para que el
        cálculo de la malla PPF sea viable con decenas de miles de objetos.
        """
        n_z  = len(z_arr)
        n_gl = len(_GL_NODES)

        u_up = np.clip(z_arr / (1.0 + np.abs(z_arr)), -1.0 + 1e-9, 1.0 - 1e-9)

        hw  = (u_up + 1.0) * 0.5        # (n_z,)
        mid = (u_up - 1.0) * 0.5        # (n_z,)

        # Nodos GL mapeados a [a_i, b_i] para cada z_i — tensor (n_z, n_gl)
        u_pts   = hw[:, None] * _GL_NODES[None, :] + mid[:, None]
        abs_u   = np.minimum(np.abs(u_pts), 1.0 - 1e-12)
        t_pts   = u_pts / (1.0 - abs_u)
        jac     = 1.0 / (1.0 - abs_u) ** 2

        # Integrando = 2 · t_nu(t) · T_{nu+1}(alpha·t·sqrt((nu+1)/(nu+t²))) · jac
        flat    = t_pts.ravel()
        t_pdf_v = stats.t.pdf(flat, df=self.nu).reshape(n_z, n_gl)
        with np.errstate(invalid="ignore", divide="ignore"):
            inner_v = (self.alpha * t_pts *
                       np.sqrt((self.nu + 1.0) /
                                np.maximum(self.nu + t_pts ** 2, 1e-300)))
        t_cdf_v = stats.t.cdf(inner_v.ravel(), df=self.nu + 1.0).reshape(n_z, n_gl)

        integrand = 2.0 * t_pdf_v * t_cdf_v * jac      # (n_z, n_gl)
        result    = hw * np.einsum("j,ij->i", _GL_WEIGHTS, integrand)
        return np.clip(result, 0.0, 1.0)

    def cdf(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return self._cdf_batch((x - self.xi) / self.omega)

    # ── PPF vía malla precomputada ────────────────────────────────────────────

    def _build_ppf_grid(self) -> None:
        """
        Construye la malla PPF usando brentq — más robusto que Newton para
        alpha extremos donde Newton diverge al cruzar regiones de PDF≈0.

        Bracket: rango de la t-Student simétrica (misma nu) ampliado por la
        asimetría de la AC — para alpha>0 la masa va a la derecha (hi más ancho);
        para alpha<0 a la izquierda (lo más ancho). Factor 12*|alpha| garantiza
        cubrir la distribución incluso para alpha=±15.
        """
        from scipy.optimize import brentq as _brentq

        u_grid = np.linspace(self._PPF_U_MIN, self._PPF_U_MAX, self._PPF_N)

        # Bracket ancho ajustado por dirección de asimetría
        t_lo = float(stats.t.ppf(1e-8, df=self.nu))
        t_hi = float(stats.t.ppf(1.0 - 1e-8, df=self.nu))
        skew_shift = float(np.clip(self.alpha, -15.0, 15.0))
        lo = (t_lo + min(skew_shift, 0) * 12.0) * self.omega + self.xi
        hi = (t_hi + max(skew_shift, 0) * 12.0) * self.omega + self.xi

        x_grid = np.empty(self._PPF_N)
        for i, u_i in enumerate(u_grid):
            try:
                x_grid[i] = _brentq(
                    lambda x: float(self._cdf_batch(
                        np.array([(x - self.xi) / self.omega]))[0]) - u_i,
                    lo, hi,
                    xtol=self._PPF_TOL, maxiter=self._PPF_ITER * 3,
                )
            except Exception as _e_brentq:
                logger.debug(
                    f"AzzaliniT._build_ppf_grid: brentq falló en u={u_i:.4f} "
                    f"(xi={self.xi:.3g}, omega={self.omega:.3g}, "
                    f"alpha={self.alpha:.3g}, nu={self.nu:.1f}) → "
                    f"{type(_e_brentq).__name__}: {_e_brentq} — usando fallback t-simétrica"
                )
                x_grid[i] = float(stats.t.ppf(u_i, df=self.nu)) * self.omega + self.xi

        # Garantizar monotonicidad estricta (brentq puede producir empates en extremos)
        for i in range(1, len(x_grid)):
            if x_grid[i] <= x_grid[i - 1]:
                x_grid[i] = x_grid[i - 1] + 1e-10

        self._ppf_u = u_grid
        self._ppf_x = x_grid

    def ppf(self, u) -> np.ndarray:
        """
        Función cuantil vía interpolación lineal sobre la malla precomputada.
        Construye la malla en la primera llamada si no existe (lazy init).
        En fitear_skewt se construye eagerly para que sea thread-safe durante
        el multiprocessing del pipeline.
        """
        if self._ppf_u is None:
            self._build_ppf_grid()
        u = np.atleast_1d(np.asarray(u, dtype=float))
        return np.interp(np.clip(u, self._ppf_u[0], self._ppf_u[-1]),
                         self._ppf_u, self._ppf_x)


# Alias de compatibilidad — el resto del código que usa SplitT como nombre
# de tipo sigue funcionando sin cambios en los type hints.
SplitT = AzzaliniT


def fitear_skewt(
    q_vals,
    taus:     list[float],
    n_starts: int = 3,
) -> AzzaliniT:
    """
    Ajusta una AzzaliniT (AC2003) a los cuantiles predichos por XGBoost.

    Diferencia clave respecto a la SplitT anterior:
    - Parámetros: xi (loc), omega (escala única), alpha (forma), nu (df).
    - Objetivo: minimizar Σ (CDF(q_τi; ·) − τi)²  en espacio NORMALIZADO.
      Usar la CDF como objetivo (no la PPF) es más eficiente porque evalúa
      la CDF en los q_τi conocidos — O(5 × n_GL) por evaluación del objetivo —
      sin necesitar búsqueda de raíces.
    - Se normaliza antes de optimizar (mediana=0, spread=1) y se desnormaliza
      al final, igual que antes, para invariancia de escala.
    - Tras encontrar los mejores parámetros, construye la malla PPF eagerly
      para que el multiprocessing de fitear_distribuciones_por_horizonte la
      compute en paralelo (no en la simulación, que puede ser serial).

    Devuelve
    --------
    AzzaliniT calibrada en la escala original de q_vals, con malla PPF lista.
    """
    if isinstance(q_vals, dict):
        q_arr = np.array([q_vals[t] for t in taus], dtype=float)
    else:
        q_arr = np.asarray(q_vals, dtype=float)
    taus_arr = np.array(taus, dtype=float)

    # ── Normalización ─────────────────────────────────────────────────────────
    med_idx   = min(range(len(taus)), key=lambda i: abs(taus[i] - 0.50))
    loc0_orig = q_arr[med_idx]
    escala    = max(q_arr.max() - q_arr.min(), 1e-9)
    q_norm    = (q_arr - loc0_orig) / escala

    # Asimetría empírica de los cuantiles: guía el alpha inicial
    spread = max(q_norm.max() - q_norm.min(), 1e-6)
    asym   = (q_norm[-1] - q_norm[med_idx]) - (q_norm[med_idx] - q_norm[0])
    alpha0 = float(np.clip(asym / (spread * 0.5 + 1e-9) * 3, -8, 8))

    # Puntos de inicio: simétrico + con asimetría detectada + asimetría opuesta
    starts = [
        [0.0, spread * 0.40,  0.0,    6.0],
        [0.0, spread * 0.35,  alpha0, 4.0],
        [0.0, spread * 0.35, -alpha0, 4.0],
    ][:n_starts]

    bounds = [
        (q_norm.min() - spread, q_norm.max() + spread),  # xi_n
        (1e-6,  8.0 * spread),                            # omega_n
        (-15.0, 15.0),                                     # alpha
        (2.01,  120.0),                                    # nu
    ]

    def objetivo(params: np.ndarray) -> float:
        xi_n, omega_n, alpha_n, nu_n = params
        if omega_n <= 0 or nu_n <= 2.0:
            return 1e6
        try:
            dist_n = AzzaliniT(xi_n, omega_n, alpha_n, nu_n)
            z_vals  = (q_norm - xi_n) / omega_n
            cdf_hat = dist_n._cdf_batch(z_vals)
            return float(np.sum((cdf_hat - taus_arr) ** 2))
        except Exception as _e_obj:
            logger.debug(f"fitear_skewt objetivo: excepción con params={params} → "
                         f"{type(_e_obj).__name__}: {_e_obj}")
            return 1e6

    mejor = None
    for x0 in starts:
        try:
            res = optimize.minimize(
                objetivo, x0, method="L-BFGS-B", bounds=bounds,
                options={"maxiter": 800, "ftol": 1e-15, "gtol": 1e-11},
            )
            if mejor is None or res.fun < mejor.fun:
                mejor = res
        except Exception as _e_opt:
            logger.debug(f"fitear_skewt: optimize.minimize falló con x0={x0} → "
                         f"{type(_e_opt).__name__}: {_e_opt}")

    # Umbral: SSE < 0.005 ~ error medio de 3 pp por cuantil — ajuste aceptable.
    if mejor is not None and mejor.fun < 0.005:
        xi_n, omega_n, alpha_n, nu_n = mejor.x
        xi    = xi_n * escala + loc0_orig
        omega = omega_n * escala
        dist  = AzzaliniT(xi, omega, alpha_n, nu_n)
        dist._build_ppf_grid()   # eager: se paraleliza con fitear_distribuciones
        return dist

    # Fallback: t-Student simétrica (alpha=0)
    logger.warning("fitear_skewt: fallo AC2003, usando fallback t-Student simétrico")
    iqr = max((q_arr[-1] - q_arr[0]) / 4.0, 1.0)
    dist = AzzaliniT(loc0_orig, iqr, 0.0, 6.0)
    dist._build_ppf_grid()
    return dist


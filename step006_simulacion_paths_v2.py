def backtest_flujo_neto_completo(
    df_preds:     pd.DataFrame,
    distribuciones: dict[tuple, "AzzaliniT"],
    taus_eval:    list[float] | None = None,
    horizontes_eval: list[int] | None = None,
    taus_input:   list[float] | None = None,
    h_col:        str = "h",
    fecha_col:    str = "fecha_t",
) -> pd.DataFrame:
    """
    Backtest de 3 piezas para flujos netos DIARIOS (no acumulados).

    Para cada (tau_eval, h):
      Pieza 1: tasa de violación I_t=1(y_real < q_tau) con Newey-West
      Pieza 2: test de duraciones Christoffersen-Pelletier
      Pieza 3: PIT = AzzaliniT_cdf(y_real) — Anderson-Darling

    El rol de 'ventana' lo juega 'h': cada horizonte es evaluado por separado.
    Mide calibración pointwise del XGBoost+AzzaliniT, no cobertura del colchón.

    INTERPRETACIÓN:
      · Una tasa de violación correcta a tau=0.05 significa que el Q05 del
        modelo captura el 5% de los peores flujos diarios a ESE horizonte.
      · Esto es condición necesaria pero no suficiente para que el colchón
        sea adecuado (el backtest acumulado mide lo segundo).
    """
    if taus_eval is None:
        taus_eval = [0.01, 0.05]
    if taus_input is None:
        taus_input = TAUS_STD
    if horizontes_eval is None:
        horizontes_eval = sorted(df_preds[h_col].unique().tolist())

    df = df_preds.copy()
    df[fecha_col] = pd.to_datetime(df[fecha_col])

    rows = []
    for tau in taus_eval:
        for h in horizontes_eval:
            df_h = (df[df[h_col] == h]
                    .sort_values(fecha_col)
                    .drop_duplicates(fecha_col)
                    .copy())

            if len(df_h) < 10:
                continue

            # ── Construir df_sim compatible con las piezas existentes ─────────
            # Reutiliza backtest_pieza1/2/3 con columnas renombradas
            q_col = f"q{int(tau * 100):02d}"
            if q_col not in df_h.columns:
                logger.warning(f"  [backtest_neto] columna {q_col} no encontrada")
                continue

            # PIT analítico desde AzzaliniT
            pits = []
            for _, row in df_h.iterrows():
                dist = distribuciones.get(
                    (pd.Timestamp(row[fecha_col]), int(row[h_col])))
                if dist is None:
                    pits.append(np.nan)
                    continue
                try:
                    pits.append(float(dist.cdf(np.array([float(row["y_realizado"])]))[0]))
                except Exception:
                    pits.append(np.nan)

            df_sim_h = pd.DataFrame({
                "fecha_t":          df_h[fecha_col].values,
                "ventana":          h,
                "tau":              tau,
                "percentil_acum":   df_h[q_col].values,    # q_tau de XGBoost
                "y_realizado_acum": df_h["y_realizado"].values,
            })

            # Pieza 3 necesita los PITs — los inyectamos en el formato esperado
            # construyendo un mini df_sim con todos los taus disponibles para PIT
            taus_q_disponibles = [t for t in taus_input
                                   if f"q{int(t*100):02d}" in df_h.columns]
            filas_multi = []
            for t_q in taus_q_disponibles:
                filas_multi.append(pd.DataFrame({
                    "fecha_t":          df_h[fecha_col].values,
                    "ventana":          h,
                    "tau":              t_q,
                    "percentil_acum":   df_h[f"q{int(t_q*100):02d}"].values,
                    "y_realizado_acum": df_h["y_realizado"].values,
                }))
            df_sim_multi = pd.concat(filas_multi, ignore_index=True) if filas_multi else df_sim_h

            r1 = backtest_pieza1_violaciones(df_sim_h, tau, h, lag_nw=h)
            r2 = backtest_pieza2_duraciones(df_sim_h, tau, h)
            r3 = backtest_pieza3_pit(df_sim_multi, h,
                                     taus_disponibles=taus_q_disponibles)

            # Estadísticos del PIT analítico
            pits_arr = np.array([p for p in pits if not np.isnan(p)])
            pit_mean_analitico = float(np.mean(pits_arr)) if len(pits_arr) > 0 else np.nan

            rows.append({
                "h":                h,
                "tau":              tau,
                # Pieza 1
                "tasa_empirica":    r1.get("tasa_empirica"),
                "ic95_lo":          r1.get("ic95_lo"),
                "ic95_hi":          r1.get("ic95_hi"),
                "p1_pasa":          r1.get("pasa"),
                # Pieza 2
                "b_weibull":        r2.get("b_weibull"),
                "lr_p_valor":       r2.get("p_valor"),
                "p2_independencia": r2.get("pasa_independencia"),
                "interp_b":         r2.get("interpretacion_b"),
                # Pieza 3
                "pit_mean":         pit_mean_analitico,
                "AD_p_valor":       r3.get("p_valor_aprox"),
                "p3_uniformidad":   r3.get("pasa_uniformidad"),
                "forma_pit":        r3.get("forma_histograma"),
            })

    df_out = pd.DataFrame(rows)
    if not df_out.empty:
        _print_backtest(df_out, label="BACKTEST FLUJO NETO")
    return df_out


